def gen_alt(t):
    items = alts(t)
    fns = []
    for a in items:
        attr = f"#[inline({a.inline})]\n" if a.inline else ""
        fns.append(f"/// Alternative to `{t.name}::{a.of}`. {a.note}\n{attr}"
                   f"pub fn {a.name}{a.sig} {{\n{indent(a.body, 4)}\n}}\n")
    code = "\n".join(fns)
    helpers = "".join(
        ALT_HELPERS[h] for h in ("F_ZERO", "F_ONE", "F_HALF", "NEAR_ONE") if h in code
    )
    code += helpers

    uses = ["use fixed::fixed::{Fixed, FixedTrait" + (", PI" if uses_pi(code) else "")
            + "};"]
    if uses_exp(code):
        uses.append("use fixed::exp::ExpTrait;")
    if uses_trig(code):
        uses.append("use fixed::trig::TrigTrait;")
    wide = wide_imports(code)
    if wide:
        uses.append("use fixed::wide::{" + ", ".join(wide) + "};")
    if ".all()" in code:
        uses.append(f"use glam::{t.bmod}::{{{t.B}, {t.B}Trait}};")
    elif t.B in code:
        uses.append(f"use glam::{t.bmod}::{t.B};")
    if "Mat3Trait::" in code:
        uses.append("use glam::mat3::Mat3Trait;")
    if "QuatTrait::" in code:
        uses.append("use glam::quat::QuatTrait;")
    uses.append(f"use glam::{t.mod}::{{{t.name}, {t.name}Trait}};")
    for d in (t.dim(3), t.dim(4)):
        if d.name != t.name and re.search(rf"\b{d.name}\b", code):
            uses.append(f"use glam::{d.mod}::{d.name};")
    return (f"{HEADER}//! Alternative implementations benchmarked against `glam::{t.mod}` "
            f"(the `alt_*` rows of\n//! `gas/{t.mod}.snap`). The library ships the cheapest "
            "formulation; the others stay here so that\n//! the comparison is reproducible "
            "across compiler upgrades.\n\n" + "\n".join(uses) + "\n\n" + code)


VARIANTS = {"pos", "neg", "zero", "true", "false", "first", "last", "some", "none", "lhs", "rhs",
            "below", "inside", "above", "near", "far", "min", "max", "clamped", "through",
            "total", "scalar", "general", "opposite", "parallel"}


def alt_benches(t, lib):
    """Every alternative runs on the inputs of the library bench(es) it competes with."""
    out = []
    for a in alts(t):
        for bench in lib:
            base = bench.name
            if base != a.of and not (base.startswith(a.of + "_")
                                     and base[len(a.of) + 1:] in VARIANTS):
                continue
            suffix = base[len(a.of):]
            if a.only and suffix[1:] not in a.only:
                continue
            names = [k for k, _ in bench.inputs]
            out.append(Bench(f"alt_{a.name}{suffix}", bench.inputs, bench.res,
                             f"alt::{a.name}({', '.join(names)})"))
    return out


def gen_bench(t):
    lib = lib_benches(t)
    benches = lib + alt_benches(t, lib)
    body = "\n".join(x.emit() for x in benches)
    pool = bench_consts(t)
    import re
    decls = "".join(f"const {name}: {ty} = {value};\n"
                    for name, (ty, value) in pool.items()
                    if re.search(rf"\b{name}\b", body))
    uses = [f"use benches::alt::{t.mod} as alt;"] if "alt::" in body else []
    uses.append("use benches::harness::{bb, sink};")
    uses.append("use fixed::fixed::Fixed;")
    uses.append(f"use glam::{t.bmod}::{t.B};")
    uses.append(f"use glam::{t.imod}::{t.I};")
    uses.append(f"use glam::{t.mod}::{{{t.name}, {t.name}Trait}};")
    uses.append(f"use glam::{t.umod}::{t.U};")
    for d in (t.dim(3), t.dim(4)):
        if d.name != t.name and re.search(rf"\b{d.name}\b", decls + body):
            uses.append(f"use glam::{d.mod}::{d.name};")
    return (f"{HEADER}//! Gas benchmarks of `glam::{t.mod}` and of the alternatives kept in "
            f"`benches::alt::{t.mod}`\n//! (the `alt_*` benches).\n//!\n"
            "//! Sierra gas is charged at the most expensive sibling branch, but steps depend "
            "on the path\n//! taken: branching functions are measured on one input per branch "
            "(`_pos` / `_neg`,\n//! `_some` / `_none`, `_first` / `_last`, ...). Every input "
            "goes through `bb` (otherwise the\n//! computation is constant-folded away) and "
            "every result through `sink`.\n\n"
            + "\n".join(uses) + "\n\n" + decls + "\n" + body)


