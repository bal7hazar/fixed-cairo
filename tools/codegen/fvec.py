ONE_RAW = 1 << 32
HALF_RAW = 1 << 31
MIN_RAW = -(1 << 63)
MAX_RAW = (1 << 63) - 1

# `is_normalized`: |length_squared - 1| <= 2^-22 (raw 1024). Derivation in `docs/DESIGN.md`
# section 3 terms: our `normalize` leaves at most 1 ULP of error per component, so the length
# squared of its result is within 2 * n + 1 <= 9 raw ULP of 1; 1024 ULP (2.4e-7) is a hundredfold
# margin for accumulated drift and still 800x tighter than the 2e-4 of glam-rs, which is itself
# ~1700 f32 epsilons (the f32 epsilon at 1.0 is 1.2e-7, ours is 2.3e-10).
NORMALIZED_EPS_RAW = 1024


class Ty:
    """One of the three vector types."""

    def __init__(self, n):
        self.n = n
        self.name = f"Vec{n}"
        self.mod = f"vec{n}"
        self.S = "Fixed"
        self.c = "xyzw"[:n]
        self.B = f"BVec{n}"
        self.bmod = f"bvec{n}"
        self.I = f"IVec{n}"
        self.imod = f"ivec{n}"
        self.U = f"UVec{n}"
        self.umod = f"uvec{n}"

    def dim(self, n):
        return Ty(n)

    def cw(self, f, name=None):
        """Component-wise struct literal: `Vec3 { x: f('x'), y: f('y'), .. }`."""
        return f"{name or self.name} {{ " + ", ".join(f"{c}: {f(c)}" for c in self.c) + " }"

    def join(self, sep, f):
        return sep.join(f(c) for c in self.c)

    def args(self, ty=None):
        return ", ".join(f"{c}: {ty or self.S}" for c in self.c)


TYPES = [Ty(n) for n in (2, 3, 4)]


