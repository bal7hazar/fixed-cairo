#!/usr/bin/env python3
"""Generates the three fixed-point vector modules of `glam` from one template.

    Vec2 / Vec3 / Vec4  (the Q32.32 scalar `fixed::Fixed`)

glam-rs generates these types from a single template too (`codegen/templates/vec.rs.tera`);
this script plays the same role, as `intvec.py` does for the integer vectors. For every type it
emits

    packages/glam/src/<m>.cairo               the library module
    packages/glam/tests/test_<m>.cairo        the tests (expected values computed here, in Python)
    packages/benches/tests/bench_<m>.cairo    one `X__base` / `X__op` pair per public function
    packages/benches/src/alt/<m>.cairo        the losing formulations, kept for comparison

usage:
    tools/codegen/fvec.py            regenerate the files (then runs `scarb fmt` on them)
    tools/codegen/fvec.py --check    exit 1 if the committed files differ from the output

The dimension-independent 80 % (consts, constructors, component-wise operations, comparisons,
reductions, rounding, conversions, operators) is templated; the dimension-specific numerics
(`cross`, `perp`, `any_orthonormal_*`, ...) are per-type snippets, not `if n ==` soup.

Every product goes through a fused kernel of `fixed::wide`: one rescale per output scalar
(docs/DESIGN.md section 2.1). The generator is split in two files (dependency-free, python >= 3.8):
    fvec.py        type model, driver, library module template, bench and `alt` templates
    fvec_tests.py  test template
"""
