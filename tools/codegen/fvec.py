HELPER_ORDER = list(HELPERS)


def helper_src(t, name):
    src = HELPERS[name]
    src = src.replace("@T@", t.name).replace("@CAST@", cast_msg(t))
    if "@CW@" in src:
        src = src.replace("@CW@", t.cw(lambda c: f"v.{c} * k"))
    return src


def used_helpers(code):
    """The helpers referenced by `code` (transitively), in declaration order."""
    used, todo = set(), [code]
    while todo:
        text = todo.pop()
        for h in HELPER_ORDER:
            if h in used:
                continue
            token = h + "(" if h in ("scaled", "to_u32") else h
            if token in text:
                used.add(h)
                todo.append(HELPERS[h])
    return [h for h in HELPER_ORDER if h in used]


