def bench_consts(t):
    """name -> (type, const value) of every operand a bench may use."""
    out = {}
    for name, vals in VECS.items():
        out[name] = (t.name, vec_const(t, vals))
    out["UNIT"] = (t.name, vec_const(t, UNITS[t.n]))
    out["UNIT_NEG"] = (t.name, vec_const(t, UNITS_NEG[t.n]))
    out["UNIT_OPP"] = (t.name, vec_const(t, [neg_val(v) for v in UNITS[t.n]]))
    for name, v in SCALARS.items():
        out[name] = ("Fixed", fixed_lit(raw_of(v)))
    for name, vals in MASKS.items():
        out[name] = (t.B, bvec_const(t, vals))
    if t.n == 3:
        out["HOM"] = ("Vec4", vec_const(t.dim(4), [(3, 2), (-7, 4), (11, 8), (5, 4)]))
    if t.n == 4:
        out["A3"] = ("Vec3", vec_const(t.dim(3), VECS["A"]))
    out["IV"] = (t.I, t.cw(lambda c: "3", t.I))
    out["UV"] = (t.U, t.cw(lambda c: "3", t.U))
    return out


