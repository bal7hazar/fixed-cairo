def fixed_lit(raw):
    if raw == 0:
        return "Fixed { raw: 0 }"
    sign = "-" if raw < 0 else ""
    return f"Fixed {{ raw: {sign}{hex(abs(raw))} }}"


def consts(t):
    T, n = t.name, t.n
    splat = lambda raw: t.cw(lambda c: fixed_lit(raw))
    unit = lambda i, raw: t.cw(lambda c: fixed_lit(raw if c == "xyzw"[i] else 0))
    out = [
        ("ZERO", T, "All zeroes.", splat(0)),
        ("ONE", T, "All ones.", splat(ONE_RAW)),
        ("NEG_ONE", T, "All negative ones.", splat(-ONE_RAW)),
        ("MIN", T, "All `Fixed::MIN` (`-2^31`).", splat(MIN_RAW)),
        ("MAX", T, "All `Fixed::MAX` (`2^31 - 2^-32`).", splat(MAX_RAW)),
    ]
    for i, c in enumerate(t.c):
        out.append((c.upper(), T, f"A unit vector pointing along the positive {c.upper()} axis.",
                    unit(i, ONE_RAW)))
    for i, c in enumerate(t.c):
        out.append((f"NEG_{c.upper()}", T,
                    f"A unit vector pointing along the negative {c.upper()} axis.",
                    unit(i, -ONE_RAW)))
    out.append(("AXES", f"[{T}; {n}]", "The unit axes.",
                "[" + ", ".join(unit(i, ONE_RAW) for i in range(n)) + "]"))
    return out


