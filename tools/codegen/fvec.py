class Bench:
    def __init__(self, name, inputs, res, op, pre=""):
        self.name, self.inputs, self.res, self.op, self.pre = name, inputs, res, op, pre

    def emit(self):
        base = "".join(f"    let _{n} = bb({e});\n" for n, e in self.inputs)
        op = "".join(f"    let {n} = bb({e});\n" for n, e in self.inputs)
        pre = f"    {self.pre}\n" if self.pre else ""
        return (f"#[test]\nfn {self.name}__base() {{\n{base}    let r = bb({self.res});\n"
                f"    sink(r);\n}}\n\n"
                f"#[test]\nfn {self.name}__op() {{\n{op}    let _r = bb({self.res});\n{pre}"
                f"    sink({self.op});\n}}\n")


def raw_of(v):
    """The raw Q32.32 value of an operand given in units (an int or a `(num, den)` pair)."""
    if isinstance(v, tuple):
        num, den = v
        return num * ONE_RAW // den
    return v * ONE_RAW


def neg_val(v):
    """The opposite of an operand given in units (an int or a `(num, den)` pair)."""
    return (-v[0], v[1]) if isinstance(v, tuple) else -v


def vec_const(t, vals):
    return t.cw(lambda c: fixed_lit(raw_of(vals[t.c.index(c)])))


def bvec_const(t, vals):
    return t.cw(lambda c: "true" if vals[t.c.index(c)] else "false", t.B)


