class Alt:
    """A losing (or reference) formulation: a free function of `benches::alt::<m>` and the
    benches that compare it with the library function `of` (same inputs, same names)."""

    def __init__(self, name, of, sig, body, note, inline="always", only=None):
        self.name, self.of, self.sig, self.body, self.note, self.inline, self.only = (
            name, of, sig, body, note, inline, only)


def to_free(t, body):
    """The body of a method, as the body of a free function of `benches::alt`."""
    import re
    return re.sub(r"\bSelf::", f"{t.name}Trait::", re.sub(r"\bself\b", "lhs", body))


