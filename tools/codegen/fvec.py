def outputs():
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import fvec_tests
    files = {}
    for t in TYPES:
        files[ROOT / f"packages/glam/src/{t.mod}.cairo"] = gen_module(t)
        files[ROOT / f"packages/glam/tests/test_{t.mod}.cairo"] = fvec_tests.gen_tests(t)
        files[ROOT / f"packages/benches/tests/bench_{t.mod}.cairo"] = gen_bench(t)
        files[ROOT / f"packages/benches/src/alt/{t.mod}.cairo"] = gen_alt(t)
    return files


def fmt(paths):
    """`scarb fmt` takes one path at most: format the workspace (the other files are clean)."""
    subprocess.run(["scarb", "fmt", "--workspace"], cwd=ROOT, check=True, capture_output=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="do not modify anything; exit 1 if the committed files are stale")
    ap.add_argument("--only", help="comma-separated kinds: src,tests,bench,alt")
    args = ap.parse_args()

    files = outputs()
    if args.only:
        kinds = {"src": "/glam/src/", "tests": "/glam/tests/", "bench": "/benches/tests/",
                 "alt": "/benches/src/alt/"}
        keep = [kinds[k] for k in args.only.split(",")]
        files = {p: c for p, c in files.items() if any(k in str(p) for k in keep)}
    before = {p: (p.read_text() if p.exists() else None) for p in files}
    for p, content in files.items():
        p.write_text(content)
    try:
        fmt(list(files))
    except subprocess.CalledProcessError as e:
        if args.check:
            for p, old in before.items():
                p.write_text(old) if old is not None else p.unlink()
        sys.exit("scarb fmt failed:\n" + e.stderr.decode())
    if not args.check:
        changed = [p for p in files if before[p] != p.read_text()]
        print(f"{len(files)} files generated, {len(changed)} changed")
        return
    stale = [p for p in files if before[p] != p.read_text()]
    for p, old in before.items():
        p.write_text(old) if old is not None else p.unlink()
    if stale:
        print("stale generated files (run tools/codegen/fvec.py):")
        for p in stale:
            print("  " + str(p.relative_to(ROOT)))
        sys.exit(1)
    print(f"{len(files)} generated files are up to date")


if __name__ == "__main__":
    main()
