def body_element_product(t, fused):
    """`x * y * ..`: the triple product is exact at the Q96.96 scale (one rescale)."""
    if not fused:
        return t.join(" * ", lambda c: f"self.{c}")
    if t.n == 2:
        return "wide_mul(self.x, self.y).narrow()"
    if t.n == 3:
        return "wide_mul(self.x, self.y).mul(self.z).narrow()"
    return ("let p = wide_mul(self.x, self.y).mul(self.z).narrow();\n"
            "wide_mul(p, self.w).narrow()")


def body_cross(t, fused):
    if fused:
        return ("Vec3 {\n"
                "    x: mul_sub(self.y, rhs.z, rhs.y, self.z),\n"
                "    y: mul_sub(self.z, rhs.x, rhs.z, self.x),\n"
                "    z: mul_sub(self.x, rhs.y, rhs.x, self.y),\n"
                "}")
    return ("Vec3 {\n"
            "    x: self.y * rhs.z - rhs.y * self.z,\n"
            "    y: self.z * rhs.x - rhs.z * self.x,\n"
            "    z: self.x * rhs.y - rhs.x * self.y,\n"
            "}")


def body_perp_dot(t, fused):
    if fused:
        return "mul_sub(self.x, rhs.y, self.y, rhs.x)"
    return "self.x * rhs.y - self.y * rhs.x"


def body_rotate(t, fused):
    if fused:
        return ("Vec2 {\n"
                "    x: mul_sub(self.x, rhs.x, self.y, rhs.y),\n"
                "    y: dot2(self.y, rhs.x, self.x, rhs.y),\n"
                "}")
    return ("Vec2 {\n"
            "    x: self.x * rhs.x - self.y * rhs.y,\n"
            "    y: self.y * rhs.x + self.x * rhs.y,\n"
            "}")


def body_from_angle(t, fused):
    if fused:
        return "let (s, c) = angle.sin_cos();\nVec2 { x: c, y: s }"
    return "Vec2 { x: angle.cos(), y: angle.sin() }"


def body_angle_to(t, fused):
    """Vec2: `atan2(perp_dot, dot)` on the two fused products; Vec3: `atan2(triple, dot)`."""
    if t.n == 2:
        if fused:
            return ("let p = mul_sub(self.x, rhs.y, self.y, rhs.x);\n"
                    "let d = dot2(self.x, rhs.x, self.y, rhs.y);\n"
                    "p.atan2(d)")
        return ("let angle = (Self::dot(self, rhs) / (Self::length(self) * Self::length(rhs)))"
                ".acos_clamped();\n"
                "if Self::perp_dot(self, rhs).is_negative() {\n    -angle\n} else {\n"
                "    angle\n}")
    if fused:
        return ("let s = det3(axis.x, axis.y, axis.z, self.x, self.y, self.z, rhs.x, rhs.y, "
                "rhs.z);\ns.atan2(Self::dot(self, rhs))")
    return "Self::dot(Self::cross(self, rhs), axis).atan2(Self::dot(self, rhs))"


def body_angle_between(t, fused):
    if fused:
        return ("let c = Self::cross(self, rhs);\n"
                "norm3(c.x, c.y, c.z).atan2(Self::dot(self, rhs))")
    return ("(Self::dot(self, rhs) / (Self::length(self) * Self::length(rhs))).acos_clamped()")


def body_sin_cos(t, fused):
    """One `sin_cos` per element (shared reduction) instead of `sin` and `cos` (two reductions)."""
    if fused:
        return ("\n".join(f"let (s{c}, c{c}) = self.{c}.sin_cos();" for c in t.c) + "\n("
                + t.cw(lambda c: f"s{c}") + ", " + t.cw(lambda c: f"c{c}") + ")")
    return "(Self::sin(self), Self::cos(self))"


def body_from_bvec(t, fused):
    """`true -> 1`, `false -> 0`: a jump per element, or the `bool -> felt252 -> i64` cast."""
    if fused:
        return t.cw(lambda c: f"if self.{c} {{ F_ONE }} else {{ F_ZERO }}")
    return t.cw(lambda c: f"Fixed {{ raw: (Into::<bool, felt252>::into(self.{c}) * "
                          f"{hex(ONE_RAW)}).try_into().unwrap() }}")


def body_from_homogeneous(t, fused):
    """Vec3: `xyz / w`. One shared `Recip` (three divisions), or three `Fixed / Fixed`."""
    if fused:
        return "let r = RecipTrait::new(v.w);\n" + "Vec3 { x: r.mul(v.x), y: r.mul(v.y), z: r.mul(v.z) }"
    return "Vec3 { x: v.x / v.w, y: v.y / v.w, z: v.z / v.w }"


def body_project(t, fused):
    """Vec4: `Vec3::from_homogeneous(self)`, or the three plain divisions."""
    if fused:
        return "Vec3Trait::from_homogeneous(self)"
    return "Vec3 { x: self.x / self.w, y: self.y / self.w, z: self.z / self.w }"


def body_smoothstep(t, fused):
    """Per element `Fixed::smoothstep` (the polynomial evaluated exactly, one rescale), or the
    literal glam-rs vector expression."""
    if fused:
        return t.cw(lambda c: f"self.{c}.smoothstep(edge0.{c}, edge1.{c})")
    return ("let t = Self::saturate((self - edge0) / (edge1 - edge0));\n"
            "let three = Self::splat(FixedTrait::from_int(3));\n"
            "let two = Self::splat(FixedTrait::from_int(2));\n"
            "t * t * (three - two * t)")


def body_rotate_axis_quat(t):
    """Vec3 `rotate_axis`: the glam-rs `Quat::from_axis_angle(axis, angle) * self`."""
    return "QuatTrait::mul_vec3(QuatTrait::from_axis_angle(axis, angle), self)"


def body_rotate_towards3(t):
    """Vec3: share the cross product and its norm between the angle and rotation axis."""
    return ("let c = Self::cross(self, rhs);\n"
            "let cn = norm3_wide(c.x, c.y, c.z);\n"
            "let angle_between = cn.to_fixed().atan2(Self::dot(self, rhs));\n"
            "// When `max_angle < 0`, rotate no further than `PI` radians away\n"
            "let angle = max_angle.clamp(angle_between - PI, angle_between);\n"
            "// The rotation axis: the normalized cross product, or an arbitrary orthogonal\n"
            "// direction when the two vectors are parallel.\n"
            "let axis = match cn.try_recip() {\n"
            "    Some(r) => " + normalized_fields(t, "r", "c") + ",\n"
            "    None => Self::normalize(Self::any_orthogonal_vector(self)),\n"
            "};\n"
            "QuatTrait::mul_vec3(QuatTrait::from_axis_angle(axis, angle), self)")


def body_rotate_towards3_recompute(t):
    """The original composition, which computes the cross product and its norm twice."""
    return ("let angle_between = Self::angle_between(self, rhs);\n"
            "let angle = max_angle.clamp(angle_between - PI, angle_between);\n"
            "let c = Self::cross(self, rhs);\n"
            "let axis = match norm3_wide(c.x, c.y, c.z).try_recip() {\n"
            "    Some(r) => " + normalized_fields(t, "r", "c") + ",\n"
            "    None => Self::normalize(Self::any_orthogonal_vector(self)),\n"
            "};\n"
            "QuatTrait::mul_vec3(QuatTrait::from_axis_angle(axis, angle), self)")


def body_any_orthogonal_vector(t):
    """Vec3: `self x Y` or `self x X`, whichever is the longer of the two."""
    return ("if self.x.abs() > self.y.abs() {\n"
            "    // `self.cross(Vec3::Y)`\n"
            "    Vec3 { x: -self.z, y: F_ZERO, z: self.x }\n"
            "} else {\n"
            "    // `self.cross(Vec3::X)`\n"
            "    Vec3 { x: F_ZERO, y: self.z, z: -self.y }\n"
            "}")


def body_slerp(t):
    """Vec3: the three branches of glam-rs, with the four divisions kept wide (`Recip`)."""
    return ("let la = norm3_wide(self.x, self.y, self.z);\n"
            "let lb = norm3_wide(rhs.x, rhs.y, rhs.z);\n"
            "let self_length = la.to_fixed();\n"
            "let rhs_length = lb.to_fixed();\n"
            "// The cosine of the angle between the two directions.\n"
            "let d = RecipTrait::new(self_length * rhs_length).mul(Self::dot(self, rhs));\n"
            "if d.abs() < NEAR_ONE {\n"
            "    let theta = d.acos_clamped();\n"
            "    let r = RecipTrait::new(theta.sin());\n"
            "    let t1 = r.mul((theta * (F_ONE - s)).sin());\n"
            "    let t2 = r.mul((theta * s).sin());\n"
            "    // The interpolated length, then one shared division per operand.\n"
            "    let len = self_length.lerp(rhs_length, s);\n"
            "    let k1 = la.recip().mul(len * t1);\n"
            "    let k2 = lb.recip().mul(len * t2);\n"
            "    Vec3 {\n"
            "        x: wide_mul(self.x, k1).add(wide_mul(rhs.x, k2)).narrow(),\n"
            "        y: wide_mul(self.y, k1).add(wide_mul(rhs.y, k2)).narrow(),\n"
            "        z: wide_mul(self.z, k1).add(wide_mul(rhs.z, k2)).narrow(),\n"
            "    }\n"
            "} else if d.is_negative() {\n"
            "    // Almost anti-parallel: turn by `PI * s` around an arbitrary orthogonal axis.\n"
            "    let q = QuatTrait::from_axis_angle(\n"
            "        Self::normalize(Self::any_orthogonal_vector(self)), PI * s,\n"
            "    );\n"
            "    let k = la.recip().mul(self_length.lerp(rhs_length, s));\n"
            "    Self::mul_scalar(QuatTrait::mul_vec3(q, self), k)\n"
            "} else {\n"
            "    // Almost parallel: the linear interpolation is the spherical one to within\n"
            "    // `theta^2 / 8`.\n"
            "    Self::lerp(self, rhs, s)\n"
            "}")


def body_slerp_sin_cos_identity(t):
    """Candidate: derive the first sine weight from one `sin` plus one `sin_cos`."""
    return ("let la = norm3_wide(lhs.x, lhs.y, lhs.z);\n"
            "let lb = norm3_wide(rhs.x, rhs.y, rhs.z);\n"
            "let self_length = la.to_fixed();\n"
            "let rhs_length = lb.to_fixed();\n"
            "let d = RecipTrait::new(self_length * rhs_length)"
            ".mul(Vec3Trait::dot(lhs, rhs));\n"
            "if d.abs() < NEAR_ONE {\n"
            "    let theta = d.acos_clamped();\n"
            "    let sin_theta = theta.sin();\n"
            "    let u = theta * s;\n"
            "    let (sin_u, cos_u) = u.sin_cos();\n"
            "    let r = RecipTrait::new(sin_theta);\n"
            "    let cot_theta = r.mul(d);\n"
            "    let t1 = wide_from(cos_u).sub(wide_mul(cot_theta, sin_u)).narrow();\n"
            "    let t2 = r.mul(sin_u);\n"
            "    let len = self_length.lerp(rhs_length, s);\n"
            "    let k1 = la.recip().mul(len * t1);\n"
            "    let k2 = lb.recip().mul(len * t2);\n"
            "    Vec3 {\n"
            "        x: wide_mul(lhs.x, k1).add(wide_mul(rhs.x, k2)).narrow(),\n"
            "        y: wide_mul(lhs.y, k1).add(wide_mul(rhs.y, k2)).narrow(),\n"
            "        z: wide_mul(lhs.z, k1).add(wide_mul(rhs.z, k2)).narrow(),\n"
            "    }\n"
            "} else if d.is_negative() {\n"
            "    let q = QuatTrait::from_axis_angle(\n"
            "        Vec3Trait::normalize(Vec3Trait::any_orthogonal_vector(lhs)), PI * s,\n"
            "    );\n"
            "    let k = la.recip().mul(self_length.lerp(rhs_length, s));\n"
            "    Vec3Trait::mul_scalar(QuatTrait::mul_vec3(q, lhs), k)\n"
            "} else {\n"
            "    Vec3Trait::lerp(lhs, rhs, s)\n"
            "}")


def body_rotate_towards(t):
    return ("let a = Self::angle_to(self, rhs);\n"
            "let abs_a = a.abs();\n"
            "// When `max_angle < 0`, rotate no further than `PI` radians away\n"
            "let angle = max_angle.clamp(abs_a - PI, abs_a);\n"
            "let angle = if a.is_negative() {\n    -angle\n} else {\n    angle\n};\n"
            "Self::rotate(Self::from_angle(angle), self)")


ROTATE_AXES = {
    "x": ("x: self.x", "y: {a}", "z: {b}"),
    "y": ("x: {a}", "y: self.y", "z: {b}"),
    "z": ("x: {a}", "y: {b}", "z: self.z"),
}


def body_rotate_axis(axis):
    """`rotate_x/y/z`: one `sin_cos`, then a fused 2-term sum per rotated component."""
    def body(t, fused):
        y, z, x = "self.y", "self.z", "self.x"
        if axis == "x":
            a, b = ((f"mul_sub({y}, c, {z}, s)", f"dot2({y}, s, {z}, c)") if fused else
                    (f"{y} * c - {z} * s", f"{y} * s + {z} * c"))
        elif axis == "y":
            a, b = ((f"dot2({x}, c, {z}, s)", f"mul_sub({z}, c, {x}, s)") if fused else
                    (f"{x} * c + {z} * s", f"{x} * (-s) + {z} * c"))
        else:
            a, b = ((f"mul_sub({x}, c, {y}, s)", f"dot2({x}, s, {y}, c)") if fused else
                    (f"{x} * c - {y} * s", f"{x} * s + {y} * c"))
        fields = [f.format(a=a, b=b) for f in ROTATE_AXES[axis]]
        return ("let (s, c) = angle.sin_cos();\nVec3 {\n" + "".join(f"    {f},\n" for f in fields)
                + "}")
    return body


def body_mul_add(t, fused):
    if fused:
        return t.cw(lambda c: f"mul_add(self.{c}, a.{c}, b.{c})")
    return t.cw(lambda c: f"self.{c} * a.{c} + b.{c}")


def body_midpoint(t, fused):
    if fused:
        return t.cw(lambda c: f"self.{c}.lerp(rhs.{c}, F_HALF)")
    return t.cw(lambda c: f"(self.{c} + rhs.{c}) * F_HALF")


def body_lerp(t, fused):
    if fused:
        return t.cw(lambda c: f"self.{c}.lerp(rhs.{c}, s)")
    return t.cw(lambda c: f"self.{c} * (F_ONE - s) + rhs.{c} * s")


def body_div_scalar(t, fused):
    if fused:
        return "let r = RecipTrait::new(rhs);\n" + t.cw(lambda c: f"r.mul(self.{c})")
    return t.cw(lambda c: f"self.{c} / rhs")


def body_normalize(t, fused):
    """`Norm` + `try_recip`: one square root, one division, one fused product per component."""
    if fused:
        return (f"let n = {norm_call(t, 'self', '_wide')};\n"
                "match n.try_recip() {\n"
                f"    Some(r) => {normalized_fields(t)},\n"
                f"    None => core::panic_with_felt252({zero_norm_msg(t)}),\n"
                "}")
    return (f"assert(!{norm_call(t, 'self', '_wide')}.is_zero(), {zero_norm_msg(t)});\n"
            f"let ({', '.join(t.c)}) = normalize{t.n}(" + t.join(", ", lambda c: f"self.{c}")
            + f");\n{t.name} {{ {', '.join(t.c)} }}")


def body_distance(t, fused):
    if fused:
        return distance_call(t, "self", "rhs")
    return f"let d = self - rhs;\n{norm_call(t, 'd')}"


def body_length_recip(t, fused):
    if fused:
        return "Self::length(self).recip()"
    return f"{norm_call(t, 'self', '_wide')}.recip().mul(F_ONE)"


def body_project_onto(t, fused):
    if fused:
        return ("let k = Self::dot(self, rhs) / Self::dot(rhs, rhs);\n"
                + t.cw(lambda c: f"rhs.{c} * k"))
    return ("let k = RecipTrait::new(Self::dot(rhs, rhs)).mul(Self::dot(self, rhs));\n"
            + t.cw(lambda c: f"rhs.{c} * k"))


def body_project_onto_wide_i128(t):
    """Benchmark-only exact Q64.64 ratio using wide integer multiplication and division."""
    num = t.join(" + ", lambda c: f"Into::<i64, i128>::into(lhs.{c}.raw) * rhs.{c}.raw.into()")
    den = t.join(" + ", lambda c: f"Into::<i64, i128>::into(rhs.{c}.raw) * rhs.{c}.raw.into()")
    return (f"let num: i128 = {num};\n"
            f"let den: i128 = {den};\n"
            "let k = Fixed {\n"
            "    raw: ((num * 0x100000000) / den).try_into().expect('Fixed: overflow'),\n"
            "};\n" + t.cw(lambda c: f"rhs.{c} * k"))


def body_reject_from(t, fused):
    if fused:
        return ("let k = Self::dot(self, rhs) / Self::dot(rhs, rhs);\n"
                + t.cw(lambda c: f"wide_from(self.{c}).sub(wide_mul(rhs.{c}, k)).narrow()"))
    return "self - Self::project_onto(self, rhs)"


def body_reject_from_normalized(t, fused):
    if fused:
        return ("let d = Self::dot(self, rhs);\n"
                + t.cw(lambda c: f"wide_from(self.{c}).sub(wide_mul(rhs.{c}, d)).narrow()"))
    return "self - Self::project_onto_normalized(self, rhs)"


def body_abs_diff_eq(t, fused):
    if fused:
        return t.join(" && ", lambda c: f"self.{c}.abs_diff_eq(rhs.{c}, max_abs_diff)")
    return "(self - rhs).abs().cmple(Self::splat(max_abs_diff)).all()"


def body_select(t, fused):
    if fused:
        return t.cw(lambda c: f"if mask.{c} {{ if_true.{c} }} else {{ if_false.{c} }}")
    return t.cw(lambda c: f"match mask.{c} {{ true => if_true.{c}, false => if_false.{c} }}")


def body_clamp(t, fused):
    if fused:
        return t.cw(lambda c: f"if self.{c} < min.{c} {{ min.{c} }} else if self.{c} > max.{c} "
                              f"{{ max.{c} }} else {{ self.{c} }}")
    return ("let v = " + t.cw(lambda c: f"if self.{c} > min.{c} {{ self.{c} }} else {{ min.{c} }}")
            + ";\n" + t.cw(lambda c: f"if v.{c} < max.{c} {{ v.{c} }} else {{ max.{c} }}"))


def body_is_negative_bitmask(t, fused):
    if fused:
        return "Self::is_negative_mask(self).bitmask()"
    return ("let m: felt252 = " + t.join(
        " + ", lambda c: f"(if self.{c}.is_negative() {{ {1 << t.c.index(c)} }} else {{ 0 }})")
        + ";\nm.try_into().unwrap()")


def min_chain(t, op, fused):
    """`min(x, min(y, min(z, w)))`: the same comparisons as glam-rs, as nested `if`s."""
    cs = list(t.c)
    if not fused:
        inner = f"self.{cs[-1]}"
        for c in reversed(cs[:-1]):
            inner = f"self.{c}.{'min' if op == '<' else 'max'}({inner})"
        return inner
    lines = [f"let m = if self.{cs[-2]} {op} self.{cs[-1]} {{ self.{cs[-2]} }} "
             f"else {{ self.{cs[-1]} }};"]
    for c in reversed(cs[:-2]):
        lines.append(f"let m = if self.{c} {op} m {{ self.{c} }} else {{ m }};")
    lines.append("m")
    return "\n".join(lines)


def position(t, op):
    cs = list(t.c)
    lines = ["let mut m = self.x;", "let mut index = 0;"]
    for i, c in enumerate(cs[1:], 1):
        last = i == len(cs) - 1
        lines.append(f"if self.{c} {op} m {{")
        if not last:
            lines.append(f"m = self.{c};")
        lines.append(f"index = {i};")
        lines.append("}")
    if t.n == 2:
        lines[0] = "let m = self.x;"
    lines.append("index")
    return "\n".join(lines)


