def dot_call(t, a, b):
    return f"dot{t.n}(" + ", ".join(f"{a}.{c}, {b}.{c}" for c in t.c) + ")"


def norm_call(t, v, suffix=""):
    return f"norm{t.n}{suffix}(" + ", ".join(f"{v}.{c}" for c in t.c) + ")"


def distance_call(t, a, b, suffix=""):
    return (f"distance{t.n}{suffix}(" + ", ".join(f"{a}.{c}" for c in t.c) + ", "
            + ", ".join(f"{b}.{c}" for c in t.c) + ")")


def normalized_fields(t, r="r", v="self"):
    """The normalized components: one fused multiplication by the shared reciprocal each."""
    return t.cw(lambda c: f"{r}.mul({v}.{c})")


