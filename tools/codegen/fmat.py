class Alt:
    """A losing (or reference) formulation: a free function of `benches::alt::<m>` and the
    benches that compare it with the library function (same inputs, same names)."""

    def __init__(self, name, targets, sig, body, note, inline="always"):
        self.name, self.targets, self.sig = name, targets, sig
        self.body, self.note, self.inline = body, note, inline


def to_free(t, body):
    """The body of a method, as the body of a free function of `benches::alt`."""
    return re.sub(r"\bSelf::", f"{t.name}Trait::", re.sub(r"\bself\b", "lhs", body))


def alts(t):
    T, n, V = t.name, t.n, t.V
    out = [
        Alt("mul_vec_unfused", [f"mul_vec{n}"], f"(lhs: {T}, rhs: {V}) -> {V}",
            to_free(t, body_mul_vec(t, False)),
            "The literal glam-rs sum of scaled columns: one rescale per product instead of one "
            f"per element of the result ({n * n} instead of {n})."),
        Alt("mul_mat_transpose", [f"mul_mat{n}"], f"(lhs: {T}, rhs: {T}) -> {T}",
            to_free(t, body_mul_mat(t, False)),
            "One transposition, then one `dot` per element instead of one `mul_vec` per column: "
            "the same kernels on transposed operands."),
        Alt("div_scalar_plain", ["div_scalar"], f"(lhs: {T}, rhs: Fixed) -> {T}",
            to_free(t, body_div_scalar(t, False)),
            f"One truncated `Fixed / Fixed` per element ({n * n} divisions) instead of the "
            "shared `Recip`."),
        Alt("inverse_plain", ["inverse", "try_inverse_some", "try_inverse_none"],
            f"(m: {T}) -> Option<{T}>", body_inverse_checked(t, False),
            f"One truncated division per element of the adjugate ({n * n} divisions) instead of "
            "the shared `Recip`: this is the formulation of glam-rs (`m * (1 / det)`).",
            inline="never"),
    ]
    if n > 2:
        out.append(Alt("from_quat_unfused", ["from_quat"], f"(rotation: Quat) -> {T}",
                       quat_axes(t, fused=False),
                       "The literal glam-rs expression: the twelve products of the nine "
                       "elements rescaled one by one (18 rescales for the 3x3 part) instead of "
                       "one fused two-term kernel per element."))
    if n == 3:
        out.append(Alt("determinant_cross", ["determinant", "determinant_singular"],
                       f"(lhs: {T}) -> Fixed", to_free(t, body_determinant(t, False)),
                       "The literal glam-rs `x_axis.dot(y_axis.cross(z_axis))`: the cross "
                       "product is floored before the dot product (two rescales) instead of the "
                       "single one of `det3`."))
    if n == 4:
        out.append(Alt("determinant_det3", ["determinant", "determinant_singular"],
                       f"(lhs: {T}) -> Fixed", to_free(t, body_determinant(t, False)),
                       "Expansion along the first row with four `det3` kernels (four rescales) "
                       "instead of the six shared 2x2 minors: the 3x3 minors are recomputed "
                       "instead of being shared.", inline="never"))
    return out


def alt_benches(t, lib):
    """Every alternative runs on the inputs of the library bench(es) it competes with."""
    by_name = {x.name: x for x in lib}
    out = []
    for a in alts(t):
        for target in a.targets:
            bench = by_name[target]
            names = [k for k, _ in bench.inputs]
            out.append(Bench(f"alt_{a.name}_{target}", bench.inputs, bench.res,
                             f"alt::{a.name}({', '.join(names)})"))
    return out


def gen_alt(t):
    fns = []
    for a in alts(t):
        attr = f"#[inline({a.inline})]\n" if a.inline else ""
        note = "\n".join(g.wrap(f"Alternative to `{t.name}::{a.targets[0]}`. {a.note}", "///"))
        fns.append(f"{note}\n{attr}pub fn {a.name}{a.sig} {{\n{indent(a.body, 4)}\n}}\n")
    code = "\n".join(fns)
    helpers = "".join(h for h, name in ((F_ZERO, "F_ZERO"), (F_ONE, "F_ONE"))
                      if re.search(rf"\b{name}\b", code))
    code += helpers
    uses = ["use fixed::fixed::Fixed;"]
    wide = wide_imports(code)
    if wide:
        uses.append("use fixed::wide::{" + ", ".join(wide) + "};")
    glam = []
    for k in (2, 3, 4):
        for kind in ("Mat", "Vec"):
            items = sorted({x for x in (f"{kind}{k}", f"{kind}{k}Trait")
                            if re.search(rf"\b{x}\b(?!Trait)" if not x.endswith("Trait")
                                         else rf"\b{x}\b", code)})
            if items:
                glam.append(f"use glam::{kind.lower()}{k}::"
                            + (items[0] if len(items) == 1 else "{" + ", ".join(items) + "}")
                            + ";")
    if re.search(r"\bQuat\b(?!Trait)", code):
        glam.append("use glam::quat::Quat;")
    uses += sorted(glam)
    return (f"{HEADER}//! Alternative implementations benchmarked against `glam::{t.mod}` "
            f"(the `alt_*` rows of\n//! `gas/{t.mod}.snap`). The library ships the cheapest "
            "formulation; the others stay here so that\n//! the comparison is reproducible "
            "across compiler upgrades.\n\n" + "\n".join(uses) + "\n\n" + code)


def gen_bench(t):
    lib = lib_benches(t)
    benches = lib + alt_benches(t, lib)
    body = "\n".join(x.emit() for x in benches)
    pool = bench_consts(t)
    decls = "".join(f"const {name}: {ty} = {value};\n"
                    for name, (ty, value) in pool.items()
                    if re.search(rf"\b{name}\b", body))
    uses = [f"use benches::alt::{t.mod} as alt;"] if "alt::" in body else []
    uses.append("use benches::harness::{bb, sink};")
    uses.append("use fixed::fixed::Fixed;")
    glam = []
    for k in (2, 3, 4):
        for kind, prefix in (("Mat", "mat"), ("Vec", "vec")):
            name = f"{kind}{k}"
            if not re.search(rf"\b{name}\b", body + decls):
                continue
            items = [name] + ([f"{name}Trait"] if re.search(rf"\b{name}Trait\b", body) else [])
            glam.append(f"use glam::{prefix}{k}::"
                        + (items[0] if len(items) == 1 else "{" + ", ".join(items) + "}") + ";")
    if re.search(r"\bQuat\b(?!Trait)", body + decls):
        glam.append("use glam::quat::Quat;")
    for k in (2, 3):
        if re.search(rf"\bAffine{k}\b", body + decls):
            glam.append(f"use glam::affine{k}::Affine{k};")
    uses += sorted(glam)
    return (f"{HEADER}//! Gas benchmarks of `glam::{t.mod}` and of the alternatives kept in "
            f"`benches::alt::{t.mod}`\n//! (the `alt_*` benches).\n//!\n"
            "//! Sierra gas is charged at the most expensive sibling branch, but steps depend "
            "on the path\n//! taken: branching functions are measured on one input per branch "
            "(`_some` / `_none`,\n//! `_first` / `_last`, ...). Every input goes through `bb` "
            "(otherwise the computation is\n//! constant-folded away) and every result through "
            "`sink`.\n\n"
            + "\n".join(uses) + "\n\n" + decls + "\n" + body)


