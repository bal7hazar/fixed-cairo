#!/usr/bin/env python3
"""Generates the three fixed-point matrix modules of `glam` from one template.

    Mat2 / Mat3 / Mat4  (column major, columns are `Vec2` / `Vec3` / `Vec4`)

glam-rs generates these types from a single template too (`codegen/templates/mat.rs.tera`); this
script plays the same role, as `fvec.py` does for the vectors. For every type it emits

    packages/glam/src/<m>.cairo               the library module
    packages/glam/tests/test_<m>.cairo        the tests (expected values computed here, in Python)
    packages/benches/tests/bench_<m>.cairo    one `X__base` / `X__op` pair per public function
    packages/benches/src/alt/<m>.cairo        the losing formulations, kept for comparison

usage:
    tools/codegen/fmat.py            regenerate the files (then runs `scarb fmt` on them)
    tools/codegen/fmat.py --check    exit 1 if the committed files differ from the output

The dimension-independent part (consts, constructors, the column-major plumbing, component-wise
operations, the matrix products, conversions, operators) is templated; the numerics that have no
dimension-independent shape (`determinant`, `inverse`, the rotation constructors, the affine
transforms) are per-type snippets, not `if n ==` soup.

Every product goes through a fused kernel of `fixed::wide`: one rescale per output scalar
(docs/DESIGN.md section 2.1). The generator is split in two files (dependency-free, python >= 3.8):
    fmat.py        type model, driver, library module template, bench and `alt` templates
    fmat_tests.py  test template
"""
