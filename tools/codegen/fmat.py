def wsum(terms):
    """A signed sum of products as one accumulator chain (`wide_mul(..).sub(..).add(..)`).

    The sign is folded into the accumulation instead of negating the narrowed result: the sum
    stays exact and a single floor applies to the signed value."""
    first = next(i for i, (_, _, s) in enumerate(terms) if s > 0)
    a, b, _ = terms[first]
    out = f"wide_mul({a}, {b})"
    for i, (a, b, s) in enumerate(terms):
        if i != first:
            out += f".{'add' if s > 0 else 'sub'}(wide_mul({a}, {b}))"
    return out


def body_mul_vec(t, fused):
    """`self * rhs`: one `dotN` per row of the result."""
    if fused:
        return t.vec(lambda j: dot_call([(t.el("self", i, j), f"rhs.{t.c[i]}")
                                         for i in range(t.n)]))
    return t.vec(lambda j: " + ".join(f"{t.el('self', i, j)} * rhs.{t.c[i]}"
                                      for i in range(t.n)))


def body_mul_mat(t, fused):
    if fused:
        return t.mat(lambda i: f"Self::mul_vec{t.n}(self, rhs.{t.cols[i]})")
    # transpose once, then one `dot` per element (the rows of `self` become columns)
    lines = ["let m = Self::transpose(self);"]
    body = t.mat(lambda i: t.vec(
        lambda j: dot_call([(f"m.{t.cols[j]}.{t.c[k]}", f"rhs.{t.cols[i]}.{t.c[k]}")
                            for k in range(t.n)])))
    return "\n".join(lines) + "\n" + body


def body_div_scalar(t, fused):
    if fused:
        return ("let r = RecipTrait::new(rhs);\n"
                + t.by_col(lambda i, j: f"r.mul({t.el('self', i, j)})"))
    return t.by_col(lambda i, j: f"{t.el('self', i, j)} / rhs")


def body_determinant(t, fused):
    n = t.n
    if n == 2:
        return mul_sub_call(t.el("self", 0, 0), t.el("self", 1, 1),
                            t.el("self", 0, 1), t.el("self", 1, 0))
    if n == 3:
        if fused:
            return "det3(" + ", ".join(t.el("self", i, j) for i in range(3)
                                       for j in range(3)) + ")"
        # the literal glam-rs `x_axis.dot(y_axis.cross(z_axis))`: the cross product is floored
        # before the dot product
        return ("let c = Vec3Trait::cross(self.y_axis, self.z_axis);\n"
                "Vec3Trait::dot(self.x_axis, c)")
    if fused:
        six = [name for name, _, _, _, _ in COEFS if name in MAT4_DET_MINORS]
        return (minors(t, six) + "\n" + mat4_cofactors(t) + "\n" + mat4_det(t))
    # expansion along the first row with four `det3` kernels instead of six shared 2x2 minors
    dets = []
    for i in range(4):
        rest = [k for k in range(4) if k != i]
        args = ", ".join(t.el("self", k, j) for k in rest for j in (1, 2, 3))
        dets.append(f"let d{i} = det3({args});")
    terms = [(t.el("self", i, 0), f"d{i}", 1 if i % 2 == 0 else -1) for i in range(4)]
    return "\n".join(dets) + "\n" + wsum(terms) + ".narrow()"


# The 18 2x2 minors of glam-rs `Mat4::inverse_checked` (`coef00` .. `coef23`), as
# `(name, a, b, c, d)` = `m[a] * m[b] - m[c] * m[d]` with `m[(i, j)]` the element of column `i`
# and row `j`. The six of them whose rows are `{2, 3}` are also what `determinant` expands on.
COEFS = [
    ("coef00", (2, 2), (3, 3), (3, 2), (2, 3)),
    ("coef02", (1, 2), (3, 3), (3, 2), (1, 3)),
    ("coef03", (1, 2), (2, 3), (2, 2), (1, 3)),
    ("coef04", (2, 1), (3, 3), (3, 1), (2, 3)),
    ("coef06", (1, 1), (3, 3), (3, 1), (1, 3)),
    ("coef07", (1, 1), (2, 3), (2, 1), (1, 3)),
    ("coef08", (2, 1), (3, 2), (3, 1), (2, 2)),
    ("coef10", (1, 1), (3, 2), (3, 1), (1, 2)),
    ("coef11", (1, 1), (2, 2), (2, 1), (1, 2)),
    ("coef12", (2, 0), (3, 3), (3, 0), (2, 3)),
    ("coef14", (1, 0), (3, 3), (3, 0), (1, 3)),
    ("coef15", (1, 0), (2, 3), (2, 0), (1, 3)),
    ("coef16", (2, 0), (3, 2), (3, 0), (2, 2)),
    ("coef18", (1, 0), (3, 2), (3, 0), (1, 2)),
    ("coef19", (1, 0), (2, 2), (2, 0), (1, 2)),
    ("coef20", (2, 0), (3, 1), (3, 0), (2, 1)),
    ("coef22", (1, 0), (3, 1), (3, 0), (1, 1)),
    ("coef23", (1, 0), (2, 1), (2, 0), (1, 1)),
]
# The six of the 18 whose rows are `{2, 3}`: `determinant` needs only those.
MAT4_DET_MINORS = ("coef00", "coef04", "coef08", "coef12", "coef16", "coef20")
# glam-rs `fac0` .. `fac5`, by the row of the result that uses them (`x`/`y`, `z`, `w`).
FACS = [("coef00", "coef02", "coef03"), ("coef04", "coef06", "coef07"),
        ("coef08", "coef10", "coef11"), ("coef12", "coef14", "coef15"),
        ("coef16", "coef18", "coef19"), ("coef20", "coef22", "coef23")]
# The three `fac` and the three elements (`vec0` .. `vec3`) each column of the adjugate uses.
ADJ_FACS = {0: (0, 1, 2), 1: (0, 3, 4), 2: (1, 3, 5), 3: (2, 4, 5)}
ADJ_VECS = {0: (1, 2, 3), 1: (0, 2, 3), 2: (0, 1, 3), 3: (0, 1, 2)}


def minors(t, names, m="self"):
    """`let coefXX = mul_sub(..);` for the named 2x2 minors."""
    out = []
    for name, a, b, c, d in COEFS:
        if name in names:
            out.append(f"let {name} = " + mul_sub_call(
                t.el(m, *a), t.el(m, *b), t.el(m, *c), t.el(m, *d)) + ";")
    return "\n".join(out)


def adjugate_terms(t, i, j, m="self"):
    """The three signed products of the adjugate element of column `i`, row `j` (Q64.64).

    The cofactor sign `(-1)^(i + j)` is folded into the accumulation: the sum is exact and a
    single floor applies to the signed value."""
    facs, vecs = ADJ_FACS[i], ADJ_VECS[i]
    comp = 0 if j <= 1 else j - 1
    col = t.cols[1] if j == 0 else t.cols[0]
    sign = 1 if (i + j) % 2 == 0 else -1
    signs = [sign, -sign, sign]
    return [(f"{m}.{col}.{t.c[vecs[k]]}", FACS[facs[k]][comp], signs[k]) for k in range(3)]


def mat4_cofactors(t, m="self"):
    """`q0` .. `q3`: the four cofactors of the first row, kept wide (Q64.64)."""
    return "\n".join(f"let q{i} = " + wsum(adjugate_terms(t, i, 0, m)) + ";" for i in range(4))


def mat4_det(t, m="self"):
    """`det = m00 * q0 + m01 * q1 + m02 * q2 + m03 * q3` (the signs are in the cofactors): four
    exact Q96.96 triple products and one rescale."""
    return "\n".join([f"q0.mul({t.el(m, 0, 0)})"]
                     + [f"    .add(q{k}.mul({t.el(m, 0, k)}))" for k in (1, 2, 3)]
                     + ["    .narrow()"])


def body_inverse_checked(t, fused):
    """The shared body of `inverse`, `try_inverse` and `inverse_or_zero`: the adjugate through
    fused kernels, then ONE division shared by every element (`Recip`)."""
    n = t.n
    div = ("let r = RecipTrait::new(det);\n", "r.mul({})") if fused \
        else ("", "{} / det")
    head, mul = div
    if n == 2:
        adj = {(0, 0): t.el("m", 1, 1), (0, 1): "-" + t.el("m", 0, 1),
               (1, 0): "-" + t.el("m", 1, 0), (1, 1): t.el("m", 0, 0)}
        return ("let det = " + mul_sub_call(t.el("m", 0, 0), t.el("m", 1, 1),
                                            t.el("m", 0, 1), t.el("m", 1, 0)) + ";\n"
                "if det == F_ZERO {\n    return None;\n}\n" + head
                + "Some(" + t.by_col(lambda i, j: mul.format(adj[(i, j)])) + ")")
    if n == 3:
        cross = ("let t{k} = " + t.vec(lambda j: mul_sub_call(
            "{a}." + t.c[(j + 1) % 3], "{b}." + t.c[(j + 2) % 3],
            "{a}." + t.c[(j + 2) % 3], "{b}." + t.c[(j + 1) % 3])) + ";")
        pairs = [(0, "m.y_axis", "m.z_axis"), (1, "m.z_axis", "m.x_axis"),
                 (2, "m.x_axis", "m.y_axis")]
        body = "\n".join(cross.replace("{k}", str(k)).replace("{a}", a).replace("{b}", b)
                         for k, a, b in pairs)
        return ("let det = det3(" + ", ".join(t.el("m", i, j) for i in range(3)
                                              for j in range(3)) + ");\n"
                "if det == F_ZERO {\n    return None;\n}\n" + body + "\n" + head
                # the adjugate is the transpose of (t0, t1, t2)
                + "Some(" + t.by_col(lambda i, j: mul.format(f"t{j}.{t.c[i]}")) + ")")
    names = [name for name, _, _, _, _ in COEFS]
    entries = "\n".join(
        f"let q{i}{j} = " + wsum(adjugate_terms(t, i, j, "m")) + ".narrow();"
        for i in range(4) for j in range(4) if j > 0)
    return (minors(t, names, "m") + "\n"
            + mat4_cofactors(t, "m") + "\n"
            + "let det = " + mat4_det(t, "m").replace("\n", "\n    ") + ";\n"
            + "if det == F_ZERO {\n    return None;\n}\n"
            + "\n".join(f"let q{i}0 = q{i}.narrow();" for i in range(4)) + "\n"
            + entries + "\n" + head
            + "Some(" + t.by_col(lambda i, j: mul.format(f"q{i}{j}")) + ")")


