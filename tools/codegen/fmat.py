def operators(t):
    T, n, N = t.name, t.n, t.n * t.n
    out = []

    def impl(docline, header, fn_sig, body, extra=""):
        out.append(f"/// {docline}\npub impl {header} {{\n{extra}    #[inline(always)]\n"
                   f"    fn {fn_sig} {{\n{indent(body, 8)}\n    }}\n}}\n")

    impl(f"`Default` is `{T}::IDENTITY`, as in glam-rs (not the all-zero derived value)."
         f"\n///\n/// Mirrors `impl Default for glam::{T}`.",
         f"{T}Default of Default<{T}>", f"default() -> {T}", f"{T}Trait::IDENTITY")
    impl(f"Element-wise `+`. Exact. Panics with the `i64_add` overflow messages.\n///\n"
         f"/// Mirrors `impl Add for glam::{T}`.",
         f"{T}Add of Add<{T}>", f"add(lhs: {T}, rhs: {T}) -> {T}",
         t.mat(lambda i: f"lhs.{t.cols[i]} + rhs.{t.cols[i]}"))
    impl(f"Element-wise `-`. Exact. Panics with the `i64_sub` overflow messages.\n///\n"
         f"/// Mirrors `impl Sub for glam::{T}`.",
         f"{T}Sub of Sub<{T}>", f"sub(lhs: {T}, rhs: {T}) -> {T}",
         t.mat(lambda i: f"lhs.{t.cols[i]} - rhs.{t.cols[i]}"))
    impl(f"Element-wise negation. Panics with `'i64_neg Underflow'` on `Fixed::MIN`.\n///\n"
         f"/// Mirrors `impl Neg for glam::{T}`.",
         f"{T}Neg of Neg<{T}>", f"neg(a: {T}) -> {T}",
         t.mat(lambda i: f"-a.{t.cols[i]}"))
    impl(f"The matrix product (see `{T}Trait::mul_mat{n}`).\n///\n"
         f"/// Mirrors `impl Mul for glam::{T}`.",
         f"{T}Mul of Mul<{T}>", f"mul(lhs: {T}, rhs: {T}) -> {T}",
         f"{T}Trait::mul_mat{n}(lhs, rhs)")
    for tr, fn, sym in [("Add", "add", "+"), ("Sub", "sub", "-"), ("Mul", "mul", "*")]:
        impl(f"Mirrors `impl {tr}Assign for glam::{T}`.",
             f"{T}{tr}Assign of {tr}Assign<{T}, {T}>", f"{fn}_assign(ref self: {T}, rhs: {T})",
             f"self = self {sym} rhs;")
    for tr, fn in [("Mul", "mul"), ("Div", "div")]:
        impl(f"Mirrors `impl {tr}Assign<f32> for glam::{T}` (see `{T}Trait::{fn}_scalar`).",
             f"{T}{tr}AssignScalar of {tr}Assign<{T}, Fixed>",
             f"{fn}_assign(ref self: {T}, rhs: Fixed)", f"self = {T}Trait::{fn}_scalar(self, rhs);")
    if n == 3:
        impl("Multiplies by a 2D affine transform embedded in a 3x3 matrix.\n///\n"
             "/// Mirrors `impl MulAssign<Affine2> for glam::Mat3`.",
             "Mat3MulAssignAffine2 of MulAssign<Mat3, Affine2>",
             "mul_assign(ref self: Mat3, rhs: Affine2)",
             "self = self * Into::<Affine2, Mat3>::into(rhs);")
    if n == 4:
        impl("Multiplies by a 3D affine transform through `Mat4Trait::mul_affine3`.\n///\n"
             "/// Mirrors `impl MulAssign<Affine3> for glam::Mat4`.",
             "Mat4MulAssignAffine3 of MulAssign<Mat4, Affine3>",
             "mul_assign(ref self: Mat4, rhs: Affine3)",
             "self = Mat4Trait::mul_affine3(self, rhs);")

    def into(docline, name, src, dst, body):
        impl(docline, f"{name} of Into<{src}, {dst}>", f"into(self: {src}) -> {dst}", body)

    into(f"Mirrors `impl From<[f32; {N}]> for glam::{T}` (column major).",
         f"FixedArrayInto{T}", t.arr, T, f"{T}Trait::from_cols_array(self)")
    into(f"Mirrors `impl From<glam::{T}> for [f32; {N}]` (column major).",
         f"{T}IntoFixedArray", T, t.arr, f"{T}Trait::to_cols_array(self)")
    into(f"Mirrors `impl From<[[f32; {n}]; {n}]> for glam::{T}` (column major).",
         f"FixedArray2dInto{T}", t.arr2d, T, f"{T}Trait::from_cols_array_2d(self)")
    into(f"Mirrors `impl From<glam::{T}> for [[f32; {n}]; {n}]` (column major).",
         f"{T}IntoFixedArray2d", T, t.arr2d, f"{T}Trait::to_cols_array_2d(self)")
    return "\n".join(out)


