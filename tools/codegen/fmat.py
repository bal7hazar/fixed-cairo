def doc(summary, mirrors, panics=None, dev=None, indent_="    "):
    semantic_dev = [
        item for item in (dev or [])
        if not item.startswith(("Exact", "As "))
        and not any(word in item.lower() for word in ("gas", "bench", "inlin"))
    ]
    if not semantic_dev and panics and any(
        "Overflow" in item or "overflow" in item for item in panics
    ):
        dev = (dev or []) + [
            "Overflow panics where f32 returns infinity or a larger finite value: "
            "docs/DESIGN.md section 3, \"overflow\".",
        ]
    return g.doc(summary, mirrors, panics, dev, indent_)


class Ty:
    """One of the three matrix types."""

    def __init__(self, n):
        self.n = n
        self.name = f"Mat{n}"
        self.mod = f"mat{n}"
        self.V = f"Vec{n}"
        self.vmod = f"vec{n}"
        self.cols = ["x_axis", "y_axis", "z_axis", "w_axis"][:n]
        self.c = "xyzw"[:n]
        self.arr = f"[Fixed; {n * n}]"
        self.arr2d = f"[[Fixed; {n}]; {n}]"

    def dim(self, n):
        return Ty(n)

    def el(self, m, i, j):
        """The element of column `i`, row `j` of the matrix expression `m`."""
        return f"{m}.{self.cols[i]}.{self.c[j]}"

    def mat(self, f, name=None):
        """`Mat3 { x_axis: f(0), y_axis: f(1), z_axis: f(2) }`."""
        return (f"{name or self.name} {{ "
                + ", ".join(f"{col}: {f(i)}" for i, col in enumerate(self.cols)) + " }")

    def vec(self, f, name=None):
        """`Vec3 { x: f(0), y: f(1), z: f(2) }`."""
        return (f"{name or self.V} {{ "
                + ", ".join(f"{c}: {f(j)}" for j, c in enumerate(self.c)) + " }")

    def by_col(self, f):
        """A matrix whose column `i` is `f(i)` applied component-wise (`f(i, j)`)."""
        return self.mat(lambda i: self.vec(lambda j: f(i, j)))


TYPES = [Ty(n) for n in (2, 3, 4)]


