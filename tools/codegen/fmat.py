def dot_call(pairs, add=None):
    """`dotN(a0, b0, a1, b1, ..)`, or `dotN_add(.., c)` when `add` is given."""
    args = ", ".join(f"{a}, {b}" for a, b in pairs)
    suffix = "_add" if add else ""
    return f"dot{len(pairs)}{suffix}({args}" + (f", {add})" if add else ")")


def mul_sub_call(a, b, c, d):
    return f"mul_sub({a}, {b}, {c}, {d})"


