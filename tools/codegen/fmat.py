def rotation_axis(t):
    """`from_axis_angle`: every element is one exact triple product plus one lifted term,
    rescaled once."""
    n = t.n
    off = {(0, 1): ("axis.z", 1), (0, 2): ("axis.y", -1), (1, 0): ("axis.z", -1),
           (1, 2): ("axis.x", 1), (2, 0): ("axis.y", 1), (2, 1): ("axis.x", -1)}

    def el(i, j):
        if i == 3 or j == 3:
            return fixed_lit(ONE_RAW if i == j else 0)
        if i == j:
            return (f"wide_mul(axis.{t.c[i]}, axis.{t.c[i]}).mul(omc)"
                    ".add(wide_from(cos).lift()).narrow()")
        a, b = sorted((i, j))
        term, sign = off[(i, j)]
        op = "add" if sign > 0 else "sub"
        return (f"wide_mul(axis.{t.c[a]}, axis.{t.c[b]}).mul(omc)"
                f".{op}(wide_mul({term}, sin).lift()).narrow()")

    return ("let (sin, cos) = angle.sin_cos();\nlet omc = F_ONE - cos;\n"
            + t.by_col(el))


def rotation_axis_named(t, axis):
    """`from_rotation_x/y/z`: the two rotated columns of the identity."""
    k = "xyz".index(axis)
    u, v = (k + 1) % 3, (k + 2) % 3

    def el(i, j):
        if i == j == k or i == 3 or j == 3:
            return fixed_lit(ONE_RAW if i == j else 0)
        if (i, j) == (u, u) or (i, j) == (v, v):
            return "cos"
        if (i, j) == (u, v):
            return "sin"
        if (i, j) == (v, u):
            return "-sin"
        return fixed_lit(0)

    return "let (sin, cos) = angle.sin_cos();\n" + t.by_col(el)


def quat_axes(t, q="rotation", scale=None, translation=None, fused=True):
    """`from_quat` and the TRS constructors: the 9 elements of the rotation matrix of a unit
    quaternion, each one an exact two-term sum of raw products rescaled once.

    `m[i][j] = 1 - 2 (b^2 + c^2)` on the diagonal and `+-2 (ab +- cd)` off it, with the doubling
    folded into the second factor (`x2 = x + x`, exact for a unit quaternion), so that every
    element is one `dot2` / `mul_sub` kernel. `scale` multiplies column `i` inside the same
    rescale (`W2 * Fixed -> T2`), never after it."""
    d = {c: f"{q}.{c}" for c in "xyzw"}
    dbl = {c: f"{c}2" for c in "xyz"}
    # (column, row) -> (a, b, c, d, sign): the element is `a * b2 (+-) c * d2`.
    off = {(0, 1): ("x", "y", "w", "z", 1), (0, 2): ("x", "z", "w", "y", -1),
           (1, 0): ("x", "y", "w", "z", -1), (1, 2): ("y", "z", "w", "x", 1),
           (2, 0): ("x", "z", "w", "y", 1), (2, 1): ("y", "z", "w", "x", -1)}

    def term(i, j):
        """The element as a wide accumulator expression (before the scale and the rescale)."""
        if i == j:
            a, b = [c for c in "xyz" if c != "xyz"[i]]
            return (f"wide_from(F_ONE).sub(wide_mul({d[a]}, {dbl[a]}))"
                    f".sub(wide_mul({d[b]}, {dbl[b]}))")
        a, b, c, e, sign = off[(i, j)]
        op = "add" if sign > 0 else "sub"
        return f"wide_mul({d[a]}, {dbl[b]}).{op}(wide_mul({d[c]}, {dbl[e]}))"

    def el(i, j):
        if i == 3:
            return fixed_lit(ONE_RAW) if j == 3 else f"{translation}.{t.c[j]}"
        if j == 3:
            return fixed_lit(0)
        if not fused:
            return unfused_el(i, j) if scale is None else f"({unfused_el(i, j)}) * {scale}.{t.c[i]}"
        acc = term(i, j)
        return acc + (f".mul({scale}.{t.c[i]}).narrow()" if scale else ".narrow()")

    def unfused_el(i, j):
        """The literal glam-rs expression: one rescale per product."""
        if i == j:
            a, b = [c for c in "xyz" if c != "xyz"[i]]
            return f"F_ONE - ({d[a]} * {dbl[a]} + {d[b]} * {dbl[b]})"
        a, b, c, e, sign = off[(i, j)]
        return f"{d[a]} * {dbl[b]} {'+' if sign > 0 else '-'} {d[c]} * {dbl[e]}"

    head = "".join(f"let {c}2 = {d[c]} + {d[c]};\n" for c in "xyz")
    if translation is None and t.n == 4:
        return head + t.by_col(lambda i, j: (fixed_lit(ONE_RAW if i == j else 0) if i == 3
                                             else el(i, j)))
    return head + t.by_col(el)


def affine2(t, scale=None, angle=False, translation=None):
    """The 2D affine constructors of `Mat3`: scale, rotation and translation in one 3x3."""
    def el(i, j):
        if i == 2:
            if j == 2:
                return fixed_lit(ONE_RAW)
            return f"{translation}.{t.c[j]}" if translation else fixed_lit(0)
        if j == 2:
            return fixed_lit(0)
        k = f"{scale}.{t.c[i]}" if scale else None
        if angle:
            if i == j:
                return f"cos * {k}" if k else "cos"
            if (i, j) == (0, 1):
                return f"sin * {k}" if k else "sin"
            return f"(-sin) * {k}" if k else "-sin"
        if i != j:
            return fixed_lit(0)
        return k if k else fixed_lit(ONE_RAW)

    head = "let (sin, cos) = angle.sin_cos();\n" if angle else ""
    return head + t.by_col(el)


def minor_match(t, src, msg):
    """`from_mat{n + 1}_minor`: the 2D `match (i, j)` of glam-rs as nested matches (no if-chain,
    no arithmetic on the indices)."""
    n = t.n
    up = t.dim(n + 1)
    arms = []
    for i in range(n + 1):
        cols = [k for k in range(n + 1) if k != i]
        inner = []
        for j in range(n + 1):
            rows = [k for k in range(n + 1) if k != j]
            value = t.mat(lambda ci: t.vec(lambda rj:
                                           f"{src}.{up.cols[cols[ci]]}.{up.c[rows[rj]]}"))
            inner.append(f"{j} => {value},")
        inner.append(f"_ => core::panic_with_felt252({msg}),")
        arms.append(f"{i} => match j {{\n" + indent("\n".join(inner), 4) + "\n},")
    arms.append(f"_ => core::panic_with_felt252({msg}),")
    return "match i {\n" + indent("\n".join(arms), 4) + "\n}"


FUSED_BODIES = {
    "mul_vec": body_mul_vec, "mul_mat": body_mul_mat, "div_scalar": body_div_scalar,
    "determinant": body_determinant, "inverse_checked": body_inverse_checked,
}


def fused_ops(t):
    """The formulations that exist as a (library, alternative) pair."""
    return ["mul_vec", "mul_mat", "div_scalar", "determinant", "inverse_checked"]


def is_fused(t, op):
    """The measured winner for (type, op). See `gas/<m>.snap`: `<op>` vs `alt_<op>`."""
    return True


