#!/usr/bin/env python3
"""Generates the swizzle traits of `glam` (glam-rs `swizzles/vec_traits.rs` + `*_impl.rs`).

    Vec2 / Vec3 / Vec4 (Q32.32)   IVec2 / IVec3 / IVec4 (i32)   UVec2 / UVec3 / UVec4 (u32)

glam-rs generates its swizzles from one template too (`codegen/templates/swizzle_traits.rs.tera`);
this script plays the same role. It emits

    packages/glam/src/swizzles.cairo            module file: the 9 submodules and their re-exports
    packages/glam/src/swizzles/<m>.cairo        one trait `<T>Swizzles` + `<T>SwizzlesImpl` per type
    packages/glam/tests/test_swizzles.cairo     the tests (expected picks written as digit codes)
    packages/benches/tests/bench_swizzles.cairo a few representative `X__base` / `X__op` pairs

usage:
    tools/codegen/swizzles.py            regenerate the files (then runs `scarb fmt` on them)
    tools/codegen/swizzles.py --check    exit 1 if the committed files differ from the output
    tools/codegen/swizzles.py --glam-src DIR   also verify that the method list of every trait
                                         equals (names and order) the one of glam-rs
                                         `DIR/vec_traits.rs` (`src/swizzles` of glam-rs 0.33.8)

Dependency-free (python >= 3.8, `scarb` on the `PATH` for the formatting pass).
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = "// GENERATED by tools/codegen/swizzles.py - do not edit by hand.\n"
COMP = "xyzw"

# (prefix, scalar description)
FAMILIES = [("", "Q32.32 `fixed::Fixed`"), ("I", "`i32`"), ("U", "`u32`")]


class Ty:
    """One of the nine swizzled vector types."""

    def __init__(self, prefix, n):
        self.prefix, self.n = prefix, n
        self.name = f"{prefix}Vec{n}"
        self.mod = f"{prefix.lower()}vec{n}"
        self.trait = f"{self.name}Swizzles"
        self.impl = f"{self.name}SwizzlesImpl"

    def dim(self, k):
        return Ty(self.prefix, k)


TYPES = [Ty(p, n) for p, _ in FAMILIES for n in (2, 3, 4)]

# ---------------------------------------------------------------------------------------------
# Method list: the order of glam-rs `vec_traits.rs`.
# ---------------------------------------------------------------------------------------------


class Method:
    """`kind` is `get` (`fn xxy(self) -> VecK`) or `with` (`fn with_xy(self, rhs: VecK) -> Self`).
    `idx` are the component indices of the name (`xxy` -> (0, 0, 1))."""

    def __init__(self, idx, kind):
        self.idx, self.kind = idx, kind
        self.k = len(idx)
        self.suffix = "".join(COMP[i] for i in idx)
        self.name = self.suffix if kind == "get" else "with_" + self.suffix

    def ret(self, t):
        return t if self.kind == "with" else t.dim(self.k)


def product(n, k):
    """All tuples of length `k` over the `n` components, in lexicographic order."""
    if k == 0:
        return [()]
    return [(i,) + rest for i in range(n) for rest in product(n, k - 1)]


def methods(t):
    """glam-rs order: the identity `xyz..` first (a default method there), then for every length
    `k` in 2..4 the getters `xx`, `xy`, ... each followed by its `with_` setter when the
    components are distinct and `k < n`, skipping the identity."""
    n = t.n
    ident = tuple(range(n))
    out = [Method(ident, "get")]
    for k in range(2, 5):
        for idx in product(n, k):
            if idx == ident:
                continue
            out.append(Method(idx, "get"))
            if k < n and len(set(idx)) == k:
                out.append(Method(idx, "with"))
    return out


# ---------------------------------------------------------------------------------------------
# Library modules
# ---------------------------------------------------------------------------------------------


def getter_expr(t, m):
    r = m.ret(t)
    if m.kind == "get":
        return f"{r.name} {{ " + ", ".join(f"{COMP[j]}: self.{COMP[i]}" for j, i in enumerate(m.idx)) + " }"
    # setter: component `idx[j]` of the result is `rhs.<j>`, the others are those of `self`
    src = {i: f"rhs.{COMP[j]}" for j, i in enumerate(m.idx)}
    return f"{t.name} {{ " + ", ".join(f"{COMP[i]}: {src.get(i, 'self.' + COMP[i])}" for i in range(t.n)) + " }"


def describe(t, m):
    if m.kind == "get":
        if m.idx == tuple(range(t.n)):
            return "Returns `self`."
        parts = ", ".join(f"self.{COMP[i]}" for i in m.idx)
        return f"Returns the `{m.ret(t).name}` `({parts})`."
    sets = ", ".join(f"`{COMP[i]}` to `rhs.{COMP[j]}`" for j, i in enumerate(m.idx))
    return f"Returns `self` with {sets}."


def signature(t, m):
    if m.kind == "get":
        return f"fn {m.name}(self: {t.name}) -> {m.ret(t).name}"
    return f"fn {m.name}(self: {t.name}, rhs: {t.dim(m.k).name}) -> {t.name}"


def library(t):
    ms = methods(t)
    scalar = dict(FAMILIES)[t.prefix]
    o = [HEADER]
    o.append(f"//! Port of glam-rs `swizzles/vec_traits.rs` (`Vec{t.n}Swizzles`) and\n")
    o.append(f"//! `swizzles/{t.mod}_impl.rs` @ 0.33.8 for `{t.name}`: {len(ms)} swizzle methods.\n")
    o.append("//!\n")
    o.append("//! The nine swizzle modules are generated from one template (`tools/codegen/swizzles.py`), as in\n")
    o.append("//! glam-rs. Every method is a struct construction from the components of `self`: no\n")
    o.append("//! arithmetic, no branch, no range check.\n\n")
    for k in (2, 3, 4):
        d = t.dim(k)
        o.append(f"use crate::{d.mod}::{d.name};\n")
    o.append("\n")
    o.append(f"/// The {len(ms)} swizzles of `{t.name}` (scalar: {scalar}): every permutation with\n")
    o.append("/// repetition of its components of length 2, 3 and 4 (`yx`, `xxyz`, ...) and the `with_*`\n")
    o.append("/// setters.\n")
    o.append("///\n")
    o.append(f"/// Mirrors `glam::Vec{t.n}Swizzles`, which glam-rs implements for the `f32`, `f64` and integer\n")
    o.append("/// vectors alike; Cairo has no associated types here, so there is one trait per vector type.\n")
    o.append("/// #### Panics\n")
    o.append("/// * Never: every method is a plain struct construction.\n")
    o.append("/// #### Deviations\n")
    o.append("/// * `Vec2` / `Vec3` / `Vec4` of the associated types are the concrete vector types of the same\n")
    o.append("///   scalar (`Vec*`, `IVec*` or `UVec*`).\n")
    o.append("/// * The `Panics` / `Deviations` sections of the methods are this one: never / none.\n")
    o.append(f"pub trait {t.trait} {{\n")
    for m in ms:
        o.append(f"    /// {describe(t, m)}\n")
        o.append("    ///\n")
        o.append(f"    /// Mirrors `glam::Vec{t.n}Swizzles::{m.name}`.\n")
        o.append(f"    {signature(t, m)};\n")
    o.append("}\n\n")
    o.append(f"pub impl {t.impl} of {t.trait} {{\n")
    for m in ms:
        o.append("    #[inline(always)]\n")
        o.append(f"    {signature(t, m)} {{\n")
        o.append(f"        {getter_expr(t, m)}\n")
        o.append("    }\n\n")
    o[-1] = "    }\n"
    o.append("}\n")
    return "".join(o)


def module_file():
    o = [HEADER]
    o.append("//! Port of glam-rs `swizzles` @ 0.33.8: the `Vec2Swizzles`, `Vec3Swizzles` and\n")
    o.append("//! `Vec4Swizzles` traits, once per vector type of glam-cairo (`Vec*`, `IVec*`, `UVec*`).\n")
    o.append("//!\n")
    o.append("//! The nine submodules are generated by `tools/codegen/swizzles.py`; the traits are\n")
    o.append("//! re-exported here (`use glam::swizzles::Vec3Swizzles;`).\n\n")
    for t in TYPES:
        o.append(f"pub mod {t.mod};\n")
    o.append("\n")
    for t in TYPES:
        o.append(f"pub use {t.mod}::{{{t.trait}, {t.impl}}};\n")
    return "".join(o)


# ---------------------------------------------------------------------------------------------
# Tests
# ---------------------------------------------------------------------------------------------

# The digit code of an expected result: digit `d` in 1..=4 is component `d - 1` of `self` (value
# `val(d)`), digit 5..=7 is component `d - 5` of `rhs`. `xxyz` is `1123`; `with_wzy` on a `Vec4`
# is `1765` (x kept, y <- rhs.z, z <- rhs.y, w <- rhs.x).


def code(t, m):
    if m.kind == "get":
        return "".join(str(i + 1) for i in m.idx)
    d = list(range(1, t.n + 1))
    for j, i in enumerate(m.idx):
        d[i] = 5 + j
    return "".join(map(str, d))


def sampled(t, m):
    """Which methods are tested: all, except that the `Vec4`-returning ones of a `Vec4` are
    sampled (256 methods per type would break the 1 200 lines cap of a test file): the 24
    permutations of `xyzw`, the `aabb` and `abab` shapes (splats included)."""
    if not (t.n == 4 and m.kind == "get" and m.k == 4):
        return True
    i = m.idx
    if len(set(i)) == 4:
        return True
    return (i[0] == i[1] and i[2] == i[3]) or (i[0] == i[2] and i[1] == i[3])


def scalar_prelude(prefix):
    if prefix == "":
        return (
            "use fixed::fixed::{Fixed, FixedTrait};\n",
            "fn val(d: u32) -> Fixed {\n"
            "    // distinct values with a non-zero fractional part: `d + d * 2^-32`\n"
            "    let d: i64 = d.into();\n"
            "    FixedTrait::from_raw(d * 4294967296 + d)\n"
            "}\n",
        )
    if prefix == "I":
        return (
            "",
            "fn val(d: u32) -> i32 {\n"
            "    // distinct values of both signs: `d * 100 - 250`\n"
            "    let d: i32 = d.try_into().unwrap();\n"
            "    d * 100 - 250\n"
            "}\n",
        )
    return (
        "",
        "fn val(d: u32) -> u32 {\n"
        "    d * 100 + 7\n"
        "}\n",
    )


def checker(t):
    """`chK(r, e, tag)`: `r` equals the vector whose components are `val` of the digits of `e`."""
    n = t.n
    digits = [
        f"val(e % 10)" if i == n - 1 else f"val(e / {10 ** (n - 1 - i)})" if i == 0
        else f"val(e / {10 ** (n - 1 - i)} % 10)"
        for i in range(n)
    ]
    lit = ", ".join(f"{COMP[i]}: {digits[i]}" for i in range(n))
    return (
        f"fn ck{n}(r: {t.name}, e: u32, tag: felt252) {{\n"
        f"    let expected = {t.name} {{ {lit} }};\n"
        f"    if r != expected {{\n"
        f"        panic_with_felt252(tag);\n"
        f"    }}\n"
        f"}}\n"
    )


def test_function(t):
    ms = [m for m in methods(t) if sampled(t, m)]
    o = [f"#[test]\nfn {t.mod}_swizzles() {{\n"]
    o.append("    let v = " + t.name + " { " + ", ".join(f"{COMP[i]}: val({i + 1})" for i in range(t.n)) + " };\n")
    for k in range(2, t.n):
        d = t.dim(k)
        o.append(f"    let r{k} = {d.name} {{ " + ", ".join(f"{COMP[j]}: val({5 + j})" for j in range(k)) + " };\n")
    for m in ms:
        if m.kind == "get":
            o.append(f"    ck{m.k}(v.{m.name}(), {code(t, m)}, '{m.name}');\n")
        else:
            o.append(f"    ck{t.n}(v.{m.name}(r{m.k}), {code(t, m)}, '{m.name}');\n")
    o.append("}\n")
    return "".join(o), len(ms), len(methods(t))


def anchors(fam):
    """Hand-written expectations, independent of the digit codes: a chain across the three
    traits (they are all in scope, so the method resolution by `self` type is exercised), a
    reversal, a setter, and a check that the checkers do detect a mismatch."""
    v2, v3, v4 = fam
    lit = lambda t, ds: f"{t.name} {{ " + ", ".join(f"{COMP[i]}: val({d})" for i, d in enumerate(ds)) + " }"
    o = ["    #[test]\n    fn anchors() {\n"]
    o.append(f"        let v = {lit(v4, [1, 2, 3, 4])};\n")
    o.append(f"        assert_eq!(v.wzyx(), {lit(v4, [4, 3, 2, 1])});\n")
    o.append(f"        assert_eq!(v.with_wzy({lit(v3, [5, 6, 7])}), {lit(v4, [1, 7, 6, 5])});\n")
    o.append(f"        assert_eq!(v.zyx().xy().yx(), {lit(v2, [2, 3])});\n")
    o.append(f"        assert_eq!(v.wx().xxy().zyxx(), {lit(v4, [1, 4, 4, 4])});\n")
    o.append("    }\n\n")
    o.append("    #[test]\n    #[should_panic(expected: 'yx')]\n    fn checker_detects_mismatch() {\n")
    o.append(f"        ck2({lit(v2, [1, 2])}.xy(), 21, 'yx');\n    }}\n")
    return "".join(o)


def test_file():
    o = [HEADER]
    o.append("//! Tests of `glam::swizzles`: the swizzle methods are pure component picks, so the tests are\n")
    o.append("//! the oracle. For every type, ONE test calls the methods on a vector of distinct values\n")
    o.append("//! (`val(1)`, `val(2)`, ..) and checks each result against a digit code written by the\n")
    o.append("//! generator (`xxyz` -> `1123`: the values of components 1, 1, 2, 3; for the `with_*` setters\n")
    o.append("//! the digits 5..7 name the components of the `rhs` vector). The `Vec4`-returning swizzles of\n")
    o.append("//! a `Vec4` (256 per type) are sampled: the 24 permutations of `xyzw`, the `aabb` and `abab`\n")
    o.append("//! shapes (splats included); every other method is tested. A mismatch panics with the\n")
    o.append("//! method name. The three scalar families live in one module each (`val` differs).\n\n")
    stats = []
    for prefix, _ in FAMILIES:
        fam = [t for t in TYPES if t.prefix == prefix]
        mod = {"": "fixed_vec", "I": "ivec", "U": "uvec"}[prefix]
        use, val = scalar_prelude(prefix)
        o.append(f"mod {mod} {{\n")
        o.append("    use core::panic_with_felt252;\n")
        o.append("    use fixed::fixed::{Fixed, FixedTrait};\n" if prefix == "" else "")
        for t in fam:
            o.append(f"    use glam::{t.mod}::{t.name};\n")
        for t in fam:
            o.append(f"    use glam::swizzles::{t.trait};\n")
        o.append("\n")
        o.append(val + "\n")
        for t in fam:
            o.append(checker(t) + "\n")
        for t in fam:
            body, tested, total = test_function(t)
            stats.append((t.name, tested, total))
            o.append(body + "\n")
        o.append(anchors(fam))
        o.append("}\n\n")
    return "".join(o), stats


# ---------------------------------------------------------------------------------------------
# Benches
# ---------------------------------------------------------------------------------------------

# Representative benches: (method name) per dimension. One per return dimension, one setter, and
# the ones with the "worst" shape (reversal, splat).
BENCH_METHODS = {
    2: ["yx", "xxy", "yxxy"],
    3: ["zy", "zyx", "zyxx", "with_xz"],
    4: ["zw", "wzy", "wzyx", "xxxx", "with_xy", "with_wzy"],
}


def bench_const(t):
    """A constant operand of type `t`."""
    vals = [3, -7, 11, 5][: t.n]
    if t.prefix == "":
        f = ", ".join(f"{COMP[i]}: Fixed {{ raw: {v * 0x100000000 + 12345:#x} }}".replace("-0x", "-0x") if v >= 0 else
                      f"{COMP[i]}: Fixed {{ raw: -{(-v) * 0x100000000 - 12345:#x} }}" for i, v in enumerate(vals))
    elif t.prefix == "I":
        f = ", ".join(f"{COMP[i]}: {v}" for i, v in enumerate(vals))
    else:
        f = ", ".join(f"{COMP[i]}: {abs(v)}" for i, v in enumerate(vals))
    return f"{t.name} {{ {f} }}"


def benches():
    o = [HEADER]
    o.append("//! Gas benchmarks of `glam::swizzles`: a few representative methods per type (a swizzle is a\n")
    o.append("//! struct construction, so the net cost of every method of a type is the same up to the\n")
    o.append("//! number of scalars built). Every input goes through `bb` (otherwise the computation is\n")
    o.append("//! constant-folded away) and every result through `sink`.\n\n")
    o.append("use benches::harness::{bb, sink};\n")
    o.append("use fixed::fixed::Fixed;\n")
    for prefix, _ in FAMILIES:
        for k in (2, 3, 4):
            o.append(f"use glam::{prefix.lower()}vec{k}::{prefix}Vec{k};\n")
    o.append("use glam::swizzles::{\n    " + ", ".join(t.trait for t in TYPES) + ",\n};\n\n")
    for t in TYPES:
        o.append(f"const {t.name.upper()}_A: {t.name} = {bench_const(t)};\n")
    o.append("\n")
    for t in TYPES:
        for name in BENCH_METHODS[t.n]:
            m = next(x for x in methods(t) if x.name == name)
            rt = m.ret(t)
            base = f"{t.mod}_{name}"
            args = f"{t.name.upper()}_A"
            if m.kind == "with":
                rhs = f"{t.dim(m.k).name.upper()}_A"
                call = f"a.{name}(bb({rhs}))"
                pre_b = f"    let _rhs = bb({rhs});\n"
                pre_o = ""
            else:
                call = f"a.{name}()"
                pre_b = pre_o = ""
            res = f"{rt.name.upper()}_A"
            o.append(f"#[test]\nfn {base}__base() {{\n    let _a = bb({args});\n{pre_b}    let r = bb({res});\n    sink(r);\n}}\n\n")
            o.append(f"#[test]\nfn {base}__op() {{\n    let a = bb({args});\n{pre_o}    let _r = bb({res});\n    sink({call});\n}}\n\n")
    return "".join(o).rstrip("\n") + "\n"


# ---------------------------------------------------------------------------------------------
# Driver
# ---------------------------------------------------------------------------------------------


def outputs():
    files = {ROOT / "packages/glam/src/swizzles.cairo": module_file()}
    for t in TYPES:
        files[ROOT / f"packages/glam/src/swizzles/{t.mod}.cairo"] = library(t)
    files[ROOT / "packages/glam/tests/test_swizzles.cairo"] = test_file()[0]
    files[ROOT / "packages/benches/tests/bench_swizzles.cairo"] = benches()
    return files


def verify_glam(path):
    """The method names and their order equal the ones of glam-rs `vec_traits.rs`."""
    text = (Path(path) / "vec_traits.rs").read_text()
    traits = re.split(r"^pub trait ", text, flags=re.M)[1:]
    ok = True
    for tr in traits:
        n = int(re.match(r"Vec(\d)Swizzles", tr).group(1))
        theirs = re.findall(r"^    fn (\w+)\(", tr, flags=re.M)
        ours = [m.name for m in methods(Ty("", n))]
        if theirs != ours:
            ok = False
            print(f"Vec{n}Swizzles: MISMATCH ({len(theirs)} glam-rs methods, {len(ours)} generated)")
            for a, b in zip(theirs, ours):
                if a != b:
                    print(f"  first difference: glam-rs `{a}` vs generated `{b}`")
                    break
        else:
            print(f"Vec{n}Swizzles: {len(ours)} methods, same names and order as glam-rs")
    return ok


def fmt():
    subprocess.run(["scarb", "fmt", "--workspace"], cwd=ROOT, check=True, capture_output=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="do not modify anything; exit 1 if the committed files are stale")
    ap.add_argument("--glam-src", help="glam-rs `src/swizzles` directory: verify the method lists")
    args = ap.parse_args()

    if args.glam_src and not verify_glam(args.glam_src):
        sys.exit(1)

    files = outputs()
    before = {p: (p.read_text() if p.exists() else None) for p in files}
    for p, content in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content)
    try:
        fmt()
    except subprocess.CalledProcessError as e:
        if args.check:
            for p, old in before.items():
                p.write_text(old) if old is not None else p.unlink()
        sys.exit("scarb fmt failed:\n" + e.stderr.decode())
    if not args.check:
        changed = [p for p in files if before[p] != p.read_text()]
        print(f"{len(files)} files generated, {len(changed)} changed")
        for name, tested, total in test_file()[1]:
            print(f"  {name}: {tested}/{total} methods tested")
        return
    stale = [p for p in files if before[p] != p.read_text()]
    for p, old in before.items():
        p.write_text(old) if old is not None else p.unlink()
    if stale:
        print("stale generated files (run tools/codegen/swizzles.py):")
        for p in stale:
            print("  " + str(p.relative_to(ROOT)))
        sys.exit(1)
    print(f"{len(files)} generated files are up to date")


if __name__ == "__main__":
    main()
