def helper_src(src):
    """cairo-lint suggests `unwrap_or(..)` for every `match` with a `None` / `Err` arm, but the
    fallback arms here are computed (or panic): they must stay lazy."""
    if "None =>" in src or "Err(" in src:
        return src.replace("#[inline(", "#[allow(manual_unwrap_or)]\n#[inline(", 1)
    return src


def used_helpers(code):
    """Transitive closure of the helpers referenced by `code`, in declaration order."""
    used, todo = set(), [code]
    while todo:
        text = todo.pop()
        for h in HELPER_ORDER:
            if h not in used and h + "(" in text:
                used.add(h)
                todo.append(HELPERS[h])
    return [h for h in HELPER_ORDER if h in used]


