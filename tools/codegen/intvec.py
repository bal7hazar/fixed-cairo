# Bodies shared by the library and by `benches::alt`
# --------------------------------------------------------------------------------------------
def felt_sum(terms):
    return " + ".join(terms)


def body_dot(t, fused, a="self", b="rhs"):
    if fused:
        terms = [f"{a}.{c}.wide_mul({b}.{c}).into()" for c in t.c]
        return f"let d: felt252 = {felt_sum(terms)};\nd.try_into().expect({ovf(t)})"
    return t.join(" + ", lambda c: f"{a}.{c} * {b}.{c}")


def body_length_squared(t, fused):
    return body_dot(t, fused, "self", "self")


def body_distance_squared(t, fused):
    if fused:
        lets = "\n".join(
            f"let d{c}: felt252 = self.{c}.into() - rhs.{c}.into();" for c in t.c)
        return (lets + "\nlet d: felt252 = " + t.join(" + ", lambda c: f"d{c} * d{c}")
                + f";\nd.try_into().expect({ovf(t)})")
    return "let d = self - rhs;\n" + t.join(" + ", lambda c: f"d.{c} * d.{c}")


def body_element_sum(t, fused):
    if fused:
        return (f"let s: felt252 = {t.join(' + ', lambda c: f'self.{c}.into()')};\n"
                f"s.try_into().expect({ovf(t)})")
    return t.join(" + ", lambda c: f"self.{c}")


def body_element_product(t, fused):
    if fused:
        return (f"let p: felt252 = {t.join(' * ', lambda c: f'self.{c}.into()')};\n"
                f"p.try_into().expect({ovf(t)})")
    return t.join(" * ", lambda c: f"self.{c}")


def mul_sub(t, fused, a, b, c, d, op="-"):
    """`a * b - c * d` (or `+`)."""
    if fused:
        return (f"{{ let v: felt252 = {a}.wide_mul({b}).into() {op} {c}.wide_mul({d}).into(); "
                f"v.try_into().expect({ovf(t)}) }}")
    return f"{a} * {b} {op} {c} * {d}"


def body_cross(t, fused):
    x = mul_sub(t, fused, "self.y", "rhs.z", "rhs.y", "self.z")
    y = mul_sub(t, fused, "self.z", "rhs.x", "rhs.z", "self.x")
    z = mul_sub(t, fused, "self.x", "rhs.y", "rhs.x", "self.y")
    if fused:
        return f"let x = {x};\nlet y = {y};\nlet z = {z};\n{t.name} {{ x, y, z }}"
    return f"{t.name} {{ x: {x}, y: {y}, z: {z} }}"


def body_perp_dot(t, fused):
    if fused:
        return (f"let v: felt252 = self.x.wide_mul(rhs.y).into() - self.y.wide_mul(rhs.x).into();\n"
                f"v.try_into().expect({ovf(t)})")
    return "self.x * rhs.y - self.y * rhs.x"


def body_rotate(t, fused):
    x = mul_sub(t, fused, "self.x", "rhs.x", "self.y", "rhs.y")
    y = mul_sub(t, fused, "self.y", "rhs.x", "self.x", "rhs.y", "+")
    if fused:
        return f"let x = {x};\nlet y = {y};\n{t.name} {{ x, y }}"
    return f"{t.name} {{ x: {x}, y: {y} }}"


def body_manhattan(t, fused):
    ad = f"abs_diff_{t.S}"
    if fused:
        return (f"let d: felt252 = {t.join(' + ', lambda c: f'{ad}(self.{c}, rhs.{c}).into()')};\n"
                f"d.try_into().expect({ovf(t)})")
    return t.join(" + ", lambda c: f"{ad}(self.{c}, rhs.{c})")


FUSED_BODIES = {
    "dot": body_dot, "length_squared": body_length_squared,
    "distance_squared": body_distance_squared, "element_sum": body_element_sum,
    "element_product": body_element_product, "cross": body_cross, "perp_dot": body_perp_dot,
    "rotate": body_rotate, "manhattan_distance": body_manhattan,
}


def fused_ops(t):
    """The fused-or-plain ops that exist on `t`."""
    ops = ["dot", "length_squared", "element_sum", "element_product", "manhattan_distance"]
    if t.signed:
        ops.append("distance_squared")
    if t.n == 3:
        ops.append("cross")
    if t.signed and t.n == 2:
        ops += ["perp_dot", "rotate"]
    return ops


def min_chain(t, op):
    """`min(x, min(y, min(z, w)))` as nested lets (same comparisons as glam-rs)."""
    cs = list(t.c)
    lines = [f"let m = if self.{cs[-2]} {op} self.{cs[-1]} {{ self.{cs[-2]} }} else {{ self.{cs[-1]} }};"]
    for c in reversed(cs[:-2]):
        lines.append(f"let m = if self.{c} {op} m {{ self.{c} }} else {{ m }};")
    lines.append("m")
    return "\n".join(lines)


def position(t, op):
    cs = list(t.c)
    lines = [f"let mut m = self.x;", "let mut index = 0;"]
    for i, c in enumerate(cs[1:], 1):
        last = i == len(cs) - 1
        lines.append(f"if self.{c} {op} m {{")
        if not last:
            lines.append(f"m = self.{c};")
        lines.append(f"index = {i};")
        lines.append("}")
    if t.n == 2:
        lines[0] = "let m = self.x;"
    lines.append("index")
    return "\n".join(lines)


def chebyshev(t):
    ad = f"abs_diff_{t.S}"
    lines = [f"let m = {ad}(self.x, rhs.x);"]
    for c in t.c[1:]:
        lines.append(f"let d = {ad}(self.{c}, rhs.{c});")
        lines.append("let m = if d > m { d } else { m };")
    lines.append("m")
    return "\n".join(lines)


def option_cw(t, f):
    """`Some(T { x: f(x)?, .. })`."""
    return "Some(" + t.cw(lambda c: f(c) + "?") + ")"


