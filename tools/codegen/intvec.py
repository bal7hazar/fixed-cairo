def consts(t):
    T, n = t.name, t.n
    one = lambda i: t.cw(lambda c: "1" if c == "xyzw"[i] else "0")
    neg = lambda i: t.cw(lambda c: "-1" if c == "xyzw"[i] else "0")
    hexs = lambda v: "0" if v == 0 else ("-" if v < 0 else "") + hex(abs(v))
    out = [
        ("ZERO", T, "All zeroes.", t.cw(lambda c: "0")),
        ("ONE", T, "All ones.", t.cw(lambda c: "1")),
    ]
    if t.signed:
        out.append(("NEG_ONE", T, "All negative ones.", t.cw(lambda c: "-1")))
    out += [
        ("MIN", T, f"All `{t.S}::MIN`.", t.cw(lambda c: hexs(t.smin))),
        ("MAX", T, f"All `{t.S}::MAX`.", t.cw(lambda c: hexs(t.smax))),
    ]
    for i, c in enumerate(t.c):
        out.append((c.upper(), T, f"A unit vector pointing along the positive {c.upper()} axis.",
                    one(i)))
    if t.signed:
        for i, c in enumerate(t.c):
            out.append((f"NEG_{c.upper()}", T,
                        f"A unit vector pointing along the negative {c.upper()} axis.", neg(i)))
    out.append(("AXES", f"[{T}; {n}]", "The unit axes.",
                "[" + ", ".join(one(i) for i in range(n)) + "]"))
    return out


def methods(t):
    T, S, n, B, o = t.name, t.S, t.n, t.B, t.other
    add_msg = f"`'{S}_add Overflow'`" + (f" / `'{S}_add Underflow'`" if t.signed else "")
    sub_msg = f"`'{S}_sub Overflow'`" + (f" / `'{S}_sub Underflow'`" if t.signed else "")
    mul_msg = f"`'{S}_mul Overflow'`"
    fused_panic = f"`{ovf(t)}` if the result does not fit `{S}`."
    fused_dev = ("Only the final result is range-checked: an intermediate product or sum that "
                 f"leaves the `{S}` range does not panic when the result fits (glam-rs panics in "
                 "debug builds and wraps in release builds).")

    def fz(op, plain_panics):
        """(body, panics, dev) of a fused-or-plain op."""
        f = is_fused(t, op)
        return (FUSED_BODIES[op](t, f), [fused_panic] if f else plain_panics,
                [fused_dev] if f else None)

    m = []
    add = lambda *a, **k: m.append(Method(*a, **k))

    add("new", f"({t.args()}) -> {T}", "Creates a new vector.", f"{T} {{ {', '.join(t.c)} }}")
    add("splat", f"(v: {S}) -> {T}", "Creates a vector with all elements set to `v`.",
        t.cw(lambda c: "v"))
    add("select", f"(mask: {B}, if_true: {T}, if_false: {T}) -> {T}",
        "Creates a vector from the elements in `if_true` and `if_false`, selecting which to use "
        "for each element of `self`.\n\nA true element in the mask uses the corresponding element "
        "from `if_true`, and false uses the element from `if_false`.",
        t.cw(lambda c: f"if mask.{c} {{ if_true.{c} }} else {{ if_false.{c} }}"))
    add("from_array", f"(a: [{S}; {n}]) -> {T}", "Creates a new vector from an array.",
        f"let [{', '.join(t.c)}] = a;\n{T} {{ {', '.join(t.c)} }}")
    add("to_array", f"(self: {T}) -> [{S}; {n}]",
        f"Converts `self` to `[{', '.join(t.c)}]`.",
        "[" + t.join(", ", lambda c: f"self.{c}") + "]")
    if n < 4:
        up, nc = t.dim(n + 1), "xyzw"[n]
        add("extend", f"(self: {T}, {nc}: {S}) -> {up.name}",
            f"Creates a {n + 1}D vector from `self` and the given `{nc}` value.",
            f"{up.name} {{ {t.join(', ', lambda c: f'{c}: self.{c}')}, {nc} }}")
    if n > 2:
        dn = t.dim(n - 1)
        add("truncate", f"(self: {T}) -> {dn.name}",
            f"Creates a {n - 1}D vector from the `{'`, `'.join(dn.c)}` elements of `self`, "
            f"discarding `{t.c[-1]}`.", dn.cw(lambda c: f"self.{c}"))
    for c in t.c:
        add(f"with_{c}", f"(self: {T}, {c}: {S}) -> {T}",
            f"Creates a {n}D vector from `self` with the given value of `{c}`.",
            t.cw(lambda k: c if k == c else f"self.{k}"))

    b, p, d = fz("dot", [f"{mul_msg} or {add_msg} if a product or the sum overflows."])
    add("dot", f"(self: {T}, rhs: {T}) -> {S}", "Computes the dot product of `self` and `rhs`.",
        b, p, d)
    add("dot_into_vec", f"(self: {T}, rhs: {T}) -> {T}",
        "Returns a vector where every component is the dot product of `self` and `rhs`.",
        "let d = Self::dot(self, rhs);\n" + t.cw(lambda c: "d"), p, d)
    if n == 3:
        b, p, d = fz("cross", [f"{mul_msg} or {sub_msg} on overflow."])
        add("cross", f"(self: {T}, rhs: {T}) -> {T}",
            "Computes the cross product of `self` and `rhs`.", b, p, d)
    add("min", f"(self: {T}, rhs: {T}) -> {T}",
        "Returns a vector containing the minimum values for each element of `self` and `rhs`."
        "\n\nIn other words this computes `[min(x, rhs.x), min(self.y, rhs.y), ..]`.",
        t.cw(lambda c: f"if self.{c} < rhs.{c} {{ self.{c} }} else {{ rhs.{c} }}"))
    add("max", f"(self: {T}, rhs: {T}) -> {T}",
        "Returns a vector containing the maximum values for each element of `self` and `rhs`."
        "\n\nIn other words this computes `[max(self.x, rhs.x), max(self.y, rhs.y), ..]`.",
        t.cw(lambda c: f"if self.{c} > rhs.{c} {{ self.{c} }} else {{ rhs.{c} }}"))
    add("clamp", f"(self: {T}, min: {T}, max: {T}) -> {T}",
        f"Component-wise clamping of values, similar to `{S}::clamp`.\n\nEach element in `min` "
        "must be less-or-equal to the corresponding element in `max`. The direct if-chain is "
        "10 to 30 % cheaper than composing `max` and `min`.",
        t.cw(lambda c: f"if self.{c} < min.{c} {{ min.{c} }} else if self.{c} > max.{c} "
                       f"{{ max.{c} }} else {{ self.{c} }}"),
        dev=["The `glam_assert!(min <= max)` precondition is not checked. When it is violated "
             "the result differs from the `self.max(min).min(max)` of glam-rs: an element below "
             "`min` clamps to `min` (glam-rs: to `max`)."])
    add("min_element", f"(self: {T}) -> {S}",
        "Returns the horizontal minimum of `self`.\n\nIn other words this computes "
        "`min(x, y, ..)`.", min_chain(t, "<"))
    add("max_element", f"(self: {T}) -> {S}",
        "Returns the horizontal maximum of `self`.\n\nIn other words this computes "
        "`max(x, y, ..)`.", min_chain(t, ">"))
    add("min_position", f"(self: {T}) -> usize",
        "Returns the index of the first minimum element of `self`.", position(t, "<"))
    add("max_position", f"(self: {T}) -> usize",
        "Returns the index of the first maximum element of `self`.", position(t, ">"))
    b, p, d = fz("element_sum", [f"{add_msg} if a partial sum overflows."])
    add("element_sum", f"(self: {T}) -> {S}",
        "Returns the sum of all elements of `self`.\n\nIn other words, this computes "
        "`self.x + self.y + ..`.", b, p, d)
    b, p, d = fz("element_product", [f"{mul_msg} if a partial product overflows."])
    add("element_product", f"(self: {T}) -> {S}",
        "Returns the product of all elements of `self`.\n\nIn other words, this computes "
        "`self.x * self.y * ..`.", b, p, d)
    for name, op, sym in [("cmpeq", "==", "=="), ("cmpne", "!=", "!="), ("cmpge", ">=", ">="),
                          ("cmpgt", ">", ">"), ("cmple", "<=", "<="), ("cmplt", "<", "<")]:
        add(name, f"(self: {T}, rhs: {T}) -> {B}",
            f"Returns a vector mask containing the result of a `{sym}` comparison for each "
            f"element of `self` and `rhs`.\n\nIn other words, this computes "
            f"`[self.x {sym} rhs.x, self.y {sym} rhs.y, ..]` for all elements.",
            t.cw(lambda c: f"self.{c} {op} rhs.{c}", B))
    if t.signed:
        add("abs", f"(self: {T}) -> {T}",
            "Returns a vector containing the absolute value of each element of `self`.",
            t.cw(lambda c: f"abs_i32(self.{c})"),
            [f"`'i32_neg Underflow'` if an element is `i32::MIN`."])
        add("signum", f"(self: {T}) -> {T}",
            "Returns a vector with elements representing the sign of `self`.\n\n"
            " - `0` if the number is zero\n - `1` if the number is positive\n"
            " - `-1` if the number is negative",
            t.cw(lambda c: f"signum_i32(self.{c})"))
        add("is_negative_bitmask", f"(self: {T}) -> u32",
            f"Returns a bitmask with the lowest {n} bits set to the sign bits from the elements "
            "of `self`.\n\nA negative element results in a `1` bit and a positive element in a "
            "`0` bit. Element `x` goes into the first lowest bit, element `y` into the second, "
            "etc.", "Self::is_negative_mask(self).bitmask()")
        add("is_negative_mask", f"(self: {T}) -> {B}",
            "Returns a mask indicating which components are negative.",
            t.cw(lambda c: f"self.{c} < 0", B))
    b, p, d = fz("length_squared", [f"{mul_msg} or {add_msg} if a square or the sum overflows."])
    add("length_squared", f"(self: {T}) -> {S}", "Computes the squared length of `self`.",
        b, p, d)
    if t.signed:
        b, p, d = fz("distance_squared", [f"{sub_msg}, {mul_msg} or {add_msg} on overflow."])
        add("distance_squared", f"(self: {T}, rhs: {T}) -> {S}",
            "Compute the squared euclidean distance between two points in space.", b, p, d)
        dz = ["`'Division by 0'` if any `rhs` element is 0.",
              "`'attempt to divide with overflow'` for `i32::MIN / -1`."]
        add("div_euclid", f"(self: {T}, rhs: {T}) -> {T}",
            "Returns the element-wise quotient of Euclidean division of `self` by `rhs`.",
            t.cw(lambda c: f"div_euclid_i32(self.{c}, rhs.{c})"), dz)
        add("rem_euclid", f"(self: {T}, rhs: {T}) -> {T}",
            "Returns the element-wise remainder of Euclidean division of `self` by `rhs`.",
            t.cw(lambda c: f"rem_euclid_i32(self.{c}, rhs.{c})"),
            ["`'Division by 0'` if any `rhs` element is 0."],
            dev=["`i32::MIN.rem_euclid(-1)` is 0, the mathematical result: `i32::rem_euclid` of "
                 "Rust panics with an overflow there (it computes `MIN % -1`)."])
    b, p, d = fz("manhattan_distance", ["`'u32_add Overflow'` if the sum overflows `u32`."])
    add("manhattan_distance", f"(self: {T}, rhs: {T}) -> u32",
        "Computes the manhattan distance between two points.\n\nSee also "
        "`checked_manhattan_distance`.", b, p)
    add("checked_manhattan_distance", f"(self: {T}, rhs: {T}) -> Option<u32>",
        "Computes the manhattan distance between two points.\n\nThis will return `None` if the "
        "result is greater than `u32::MAX`.",
        "let d: felt252 = "
        + t.join(" + ", lambda c: f"abs_diff_{S}(self.{c}, rhs.{c}).into()") + ";\nd.try_into()")
    add("chebyshev_distance", f"(self: {T}, rhs: {T}) -> u32",
        "Computes the chebyshev distance between two points.", chebyshev(t))
    if t.signed and n == 2:
        add("perp", f"(self: {T}) -> {T}", "Returns a vector that is equal to `self` rotated by "
            "90 degrees.", f"{T} {{ x: -self.y, y: self.x }}",
            ["`'i32_neg Underflow'` if `self.y` is `i32::MIN`."])
        b, p, d = fz("perp_dot", [f"{mul_msg} or {sub_msg} on overflow."])
        add("perp_dot", f"(self: {T}, rhs: {T}) -> {S}",
            "The perpendicular dot product of `self` and `rhs`. Also known as the wedge product, "
            "2D cross product, and determinant.", b, p, d)
        b, p, d = fz("rotate", [f"{mul_msg}, {add_msg} or {sub_msg} on overflow."])
