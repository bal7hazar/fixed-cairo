I32_MIN, I32_MAX, U32_MAX = -(2**31), 2**31 - 1, 2**32 - 1


class Ty:
    """One of the six vector types."""

    def __init__(self, signed, n):
        self.signed, self.n = signed, n
        p = "I" if signed else "U"
        self.name = f"{p}Vec{n}"
        self.mod = f"{p.lower()}vec{n}"
        self.S = "i32" if signed else "u32"
        self.c = "xyzw"[:n]
        self.B = f"BVec{n}"
        self.bmod = f"bvec{n}"
        self.smin = I32_MIN if signed else 0
        self.smax = I32_MAX if signed else U32_MAX

    @property
    def other(self):
        """The vector of the same dimension and of the other signedness."""
        return Ty(not self.signed, self.n)

    def dim(self, n):
        return Ty(self.signed, n)

    def cw(self, f, name=None):
        """Component-wise struct literal: `T { x: f('x'), y: f('y'), .. }`."""
        return f"{name or self.name} {{ " + ", ".join(f"{c}: {f(c)}" for c in self.c) + " }"

    def join(self, sep, f):
        return sep.join(f(c) for c in self.c)

    def args(self, ty=None):
        return ", ".join(f"{c}: {ty or self.S}" for c in self.c)


TYPES = [Ty(s, n) for s in (True, False) for n in (2, 3, 4)]

# --------------------------------------------------------------------------------------------
# Formulation choices. Every entry is backed by the `alt_*` rows of gas/<m>.snap; the other
# formulation of each pair is emitted in `benches::alt::<m>`.
#
# "fused": widen every product / term to felt252 (no range check), accumulate, and convert back
#          once (one range-checked conversion per output scalar, 'overflow' panic).
# "plain": the literal glam-rs expression with the panicking corelib operators.
# --------------------------------------------------------------------------------------------
FUSED_OPS = ["dot", "length_squared", "distance_squared", "element_sum", "element_product",
             "cross", "perp_dot", "rotate", "manhattan_distance"]


def is_fused(t, op):
    """The measured winner for (type, op). See gas/*.snap: `<op>` vs `alt_<op>_*`."""
    if op in ("element_sum", "element_product", "manhattan_distance"):
        # one conversion against n - 1 checked operations: a tie (IVec2) or a loss (UVec2) at n = 2
        return t.n >= 3
    return True


def ovf(t):
    return f"'{t.name}: overflow'"


# --------------------------------------------------------------------------------------------
# Doc helpers
# --------------------------------------------------------------------------------------------
def wrap(text, prefix):
    out = []
    for para in text.split("\n\n"):
        if para.startswith(" "):  # preformatted
            out += [(prefix + " " + line[1:]).rstrip() for line in para.split("\n")]
        else:
            out += textwrap.wrap(" ".join(para.split()), width=99 - len(prefix) - 1,
                                 initial_indent=prefix + " ", subsequent_indent=prefix + " ")
        out.append(prefix)
    return out[:-1]


def bullets(items, p):
    out = []
    for item in items:
        out += textwrap.wrap(" ".join(item.split()), width=98 - len(p),
                             initial_indent=p + " * ", subsequent_indent=p + "   ")
    return out


def doc(summary, mirrors, panics=None, dev=None, indent="    "):
    dev = dev or []
    notes = [
        item for item in dev
        if item.startswith(("Exact", "As `", "As ["))
        or "passed by value" in item
        or any(word in item.lower() for word in ("gas", "bench", "inlin"))
    ]
    dev = [item for item in dev if item not in notes]
    if notes:
        summary += "\n\n" + " ".join(notes)
    p = indent + "///"
    lines = wrap(summary, p) + [p, f"{p} Mirrors `{mirrors}`.", f"{p} #### Panics"]
    lines += bullets(panics or ["Never."], p)
    lines.append(f"{p} #### Deviations")
    lines += bullets(dev or ["None."], p)
    return "\n".join(lines)


class Method:
    def __init__(self, name, sig, summary, body, panics=None, dev=None, mirrors=None,
                 inline=True, note=None):
        self.name, self.sig, self.summary, self.body = name, sig, summary, body
        self.panics, self.dev, self.mirrors, self.inline, self.note = (
            panics, dev, mirrors, inline, note)


