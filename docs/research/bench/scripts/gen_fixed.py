#!/usr/bin/env python3
"""Generates tests/scalar.cairo, tests/composite.cairo and tests/correctness.cairo.

Same `X__base` / `X__op` convention as gen_prims.py. Inputs are raw Q32.32 i64 constants routed
through `#[inline(never)]` constructors (`mk*`), so nothing can be constant-folded and the
construction cost (which differs per representation) cancels out in op - base.
"""
import math
import os
from fractions import Fraction

REPS = [  # (module tag, type path, type name)
    ("mag", "bench::fixed::mag::FMag"),
    ("magi", "bench::fixed::magi::FMagI"),
    ("i64n", "bench::fixed::i64n::FI64N"),
    ("i64b", "bench::fixed::i64b::FI64"),
    ("felt", "bench::fixed::felt::FFelt"),
]
ONE = 1 << 32


def raw(x):
    return int(math.floor(x * ONE))


A, B_, C = 3.14159265, -2.71828183, 1.41421356
V1 = (1.25, -2.5, 3.75)
V2 = (-0.7, 4.2, 0.35)
Q1 = (0.18257419, 0.36514837, 0.54772256, 0.73029674)  # unit quaternion
Q2 = (-0.5, 0.5, -0.5, 0.5)
M3A = [0.9, -0.1, 0.4, 0.2, 1.1, -0.3, -0.5, 0.6, 0.8]
M3B = [1.5, 0.25, -0.75, -1.25, 0.5, 2.0, 0.1, -0.2, 0.3]
M4A = [0.9, -0.1, 0.4, 0.0, 0.2, 1.1, -0.3, 0.0, -0.5, 0.6, 0.8, 0.0, 1.0, 2.0, 3.0, 1.0]
M4B = [1.5, 0.25, -0.75, 0.0, -1.25, 0.5, 2.0, 0.0, 0.1, -0.2, 0.3, 0.0, -4.0, 5.0, 6.0, 1.0]


def lit(v):
    r = raw(v)
    return str(r)


def span(vals):
    return "array![" + ", ".join(lit(v) for v in vals) + "].span()"


def vec(vals):
    return ", ".join(lit(v) for v in vals)


HEADER = '''// GENERATED by scripts/gen_fixed.py -- do not edit by hand.
use bench::fixed::{Fused, Real};
use bench::glam::{self, Mat3, Mat4, Quat, Vec3, mk, mk_mat3, mk_mat4, mk_quat, mk_vec3};
use bench::harness::{bb, sink};
'''


def pair(name, prelude, rdecl, rtype, expr):
    pre = "".join(f"    {l}\n" for l in prelude)
    return (
        f"#[test]\n#[allow(unused_variables)]\nfn {name}__base() {{\n{pre}    let r: {rtype} = {rdecl};\n    sink::<{rtype}>(r);\n}}\n"
        f"#[test]\n#[allow(unused_variables)]\nfn {name}__op() {{\n{pre}    let r: {rtype} = {rdecl};\n    sink::<{rtype}>({expr});\n}}\n"
    )


def scalar_tests():
    out = [HEADER]
    for tag, ty in REPS:
        T = ty.split("::")[-1]
        out.append(f"mod {tag} {{\n    use super::*;\n    use {ty};\n")
        two = [f"let a: {T} = mk({lit(A)});", f"let b: {T} = mk({lit(B_)});"]
        pos = [f"let a: {T} = mk({lit(A)});", f"let b: {T} = mk({lit(C)});"]
        neg1 = [f"let a: {T} = mk({lit(B_)});"]
        pos1 = [f"let a: {T} = mk({lit(A)});"]
        rT, rB, rI = ("mk(1)", T), ("bb(true)", "bool"), ("bb(1)", "i32")
        specs = [
            ("add_mixed_signs", two, rT, "a + b"),
            ("add_same_sign", pos, rT, "a + b"),
            ("sub_mixed_signs", two, rT, "a - b"),
            ("sub_same_sign", pos, rT, "a - b"),
            ("mul", two, rT, "a * b"),
            ("mul_pos", pos, rT, "a * b"),
            ("div", two, rT, "a / b"),
            ("div_pos", pos, rT, "a / b"),
            ("neg", neg1, rT, "-a"),
            ("abs_of_negative", neg1, rT, "a.abs()"),
            ("abs_of_positive", pos1, rT, "a.abs()"),
            ("lt_mixed_signs", two, rB, "a < b"),
            ("lt_same_sign", pos, rB, "a < b"),
            ("le_same_sign", pos, rB, "a <= b"),
            ("eq", pos, rB, "a == b"),
            ("from_int", ["let i = bb::<i32>(-7);"], rT, "Real::from_int(i)"),
            ("to_int_of_negative", neg1, rI, "a.to_int()"),
            ("floor_of_negative", neg1, rT, "a.floor()"),
            ("floor_of_positive", pos1, rT, "a.floor()"),
            ("round_of_negative", neg1, rT, "a.round()"),
            ("sqrt", pos1, rT, "a.sqrt()"),
            ("mul_add_chain", two + [f"let c: {T} = mk({lit(C)});"], rT, "a * b + c"),
            ("lerp", two + [f"let c: {T} = mk({lit(0.3)});"], rT, "a + (b - a) * c"),
        ]
        for name, pre, (rdecl, rtype), expr in specs:
            out.append(pair(name, pre, rdecl, rtype, expr))
        out.append("}\n")
    # Q64.64 (F)
    out.append("mod q64 {\n    use super::*;\n    use bench::fixed::q64::{self, FQ64};\n")
    pre = [f"let a = q64::from_raw(bb::<i128>({raw(A) << 32}));", f"let b = q64::from_raw(bb::<i128>({raw(B_) << 32}));"]
    for name, expr in [("add_mixed_signs", "q64::add(a, b)"), ("mul", "q64::mul(a, b)"),
                       ("mul_u256_path", "q64::mul_u256(a, b)"), ("div", "q64::div(a, b)")]:
        out.append(pair(name, pre, "q64::from_raw(bb::<i128>(1))", "FQ64", expr))
    out.append("}\n")
    return "\n".join(out)


COMPOSITES = [
    # name, prelude builder, result decl, result type, expr
    ("vec3_add", lambda T: [f"let a: Vec3<{T}> = mk_vec3({vec(V1)});", f"let b: Vec3<{T}> = mk_vec3({vec(V2)});"],
     "mk_vec3(1, 1, 1)", "Vec3<{T}>", "glam::vec3_add(a, b)"),
    ("vec3_scale", lambda T: [f"let a: Vec3<{T}> = mk_vec3({vec(V1)});", f"let s: {T} = mk({lit(B_)});"],
     "mk_vec3(1, 1, 1)", "Vec3<{T}>", "glam::vec3_scale(a, s)"),
    ("vec3_dot", lambda T: [f"let a: Vec3<{T}> = mk_vec3({vec(V1)});", f"let b: Vec3<{T}> = mk_vec3({vec(V2)});"],
     "mk(1)", "{T}", "glam::dot(a, b)"),
    ("vec3_cross", lambda T: [f"let a: Vec3<{T}> = mk_vec3({vec(V1)});", f"let b: Vec3<{T}> = mk_vec3({vec(V2)});"],
     "mk_vec3(1, 1, 1)", "Vec3<{T}>", "glam::cross(a, b)"),
    ("vec3_length", lambda T: [f"let a: Vec3<{T}> = mk_vec3({vec(V1)});"], "mk(1)", "{T}", "glam::length(a)"),
    ("vec3_normalize", lambda T: [f"let a: Vec3<{T}> = mk_vec3({vec(V1)});"], "mk_vec3(1, 1, 1)", "Vec3<{T}>",
     "glam::normalize(a)"),
    ("mat3_mul_vec3", lambda T: [f"let m: Mat3<{T}> = mk_mat3({span(M3A)});", f"let v: Vec3<{T}> = mk_vec3({vec(V1)});"],
     "mk_vec3(1, 1, 1)", "Vec3<{T}>", "glam::mat3_mul_vec3(m, v)"),
    ("mat3_mul_mat3", lambda T: [f"let a: Mat3<{T}> = mk_mat3({span(M3A)});", f"let b: Mat3<{T}> = mk_mat3({span(M3B)});"],
     f"mk_mat3({span(M3A)})", "Mat3<{T}>", "glam::mat3_mul_mat3(a, b)"),
    ("mat4_mul_mat4", lambda T: [f"let a: Mat4<{T}> = mk_mat4({span(M4A)});", f"let b: Mat4<{T}> = mk_mat4({span(M4B)});"],
     f"mk_mat4({span(M4A)})", "Mat4<{T}>", "glam::mat4_mul_mat4(a, b)"),
    ("quat_mul_quat", lambda T: [f"let a: Quat<{T}> = mk_quat({vec(Q1)});", f"let b: Quat<{T}> = mk_quat({vec(Q2)});"],
     "mk_quat(1, 1, 1, 1)", "Quat<{T}>", "glam::quat_mul(a, b)"),
    ("quat_rotate_vec3", lambda T: [f"let q: Quat<{T}> = mk_quat({vec(Q1)});", f"let v: Vec3<{T}> = mk_vec3({vec(V1)});"],
     "mk_vec3(1, 1, 1)", "Vec3<{T}>", "glam::quat_rotate(q, v)"),
]


def composite_tests():
    out = [HEADER]
    for tag, ty in REPS:
        T = ty.split("::")[-1]
        out.append(f"mod {tag} {{\n    use super::*;\n    use {ty};\n")
        for name, pre, rdecl, rtype, expr in COMPOSITES:
            out.append(pair(name, pre(T), rdecl, rtype.format(T=T), expr))
        if tag in ("i64b", "mag"):
            out.append(pair("mat3_mul_mat3_span_loop",
                            [f"let a: Span<{T}> = glam::mk_span9({span(M3A)});", f"let b: Span<{T}> = glam::mk_span9({span(M3B)});"],
                            f"glam::mk_span9::<{T}>({span(M3A)}).into()", f"Array<{T}>", "glam::mat3_mul_mat3_span_loop(a, b)"))
        out.append("}\n")
    return "\n".join(out)


# ------------------------------------------------------------------ correctness
def fx(v):  # the exact value actually represented by the raw constant
    return Fraction(raw(v), ONE)


def near(got, want, tol):
    w = int(math.floor(want * ONE))
    return f"    assert_near({got}, {w}, {tol});\n"


def correctness_tests():
    out = [HEADER, '''
fn assert_near(got: i64, want: i64, tol: i64) {
    let d = if got > want { got - want } else { want - got };
    assert!(d <= tol, "got {} want {} (tol {})", got, want, tol);
}
''']
    a, b, c = fx(A), fx(B_), fx(C)
    v1, v2 = [fx(v) for v in V1], [fx(v) for v in V2]
    q1, q2 = [fx(v) for v in Q1], [fx(v) for v in Q2]
    m3a, m3b = [fx(v) for v in M3A], [fx(v) for v in M3B]
    m4a, m4b = [fx(v) for v in M4A], [fx(v) for v in M4B]
    dot = sum(x * y for x, y in zip(v1, v2))
    cross = [v1[1] * v2[2] - v2[1] * v1[2], v1[2] * v2[0] - v2[2] * v1[0], v1[0] * v2[1] - v2[0] * v1[1]]
    ln = math.sqrt(float(sum(x * x for x in v1)))
    mv = [sum(m3a[3 * col + r] * v1[col] for col in range(3)) for r in range(3)]
    mm = [sum(m3a[3 * k + r] * m3b[3 * col + k] for k in range(3)) for col in range(3) for r in range(3)]
    m4 = [sum(m4a[4 * k + r] * m4b[4 * col + k] for k in range(4)) for col in range(4) for r in range(4)]
    ax, ay, az, aw = q1
    bx, by, bz, bw = q2
    qm = [aw * bx + ax * bw + ay * bz - az * by, aw * by - ax * bz + ay * bw + az * bx,
          aw * bz + ax * by - ay * bx + az * bw, aw * bw - ax * bx - ay * by - az * bz]
    # rotation (glam formula)
    bv = [ax, ay, az]
    b2 = sum(x * x for x in bv)
    d = sum(x * y for x, y in zip(v1, bv))
    cr = [bv[1] * v1[2] - v1[1] * bv[2], bv[2] * v1[0] - v1[2] * bv[0], bv[0] * v1[1] - v1[0] * bv[1]]
    rot = [v1[i] * (aw * aw - b2) + bv[i] * (2 * d) + cr[i] * (2 * aw) for i in range(3)]
    for tag, ty in REPS:
        T = ty.split("::")[-1]
        body = f"    let a: {T} = mk({lit(A)});\n    let b: {T} = mk({lit(B_)});\n    let c: {T} = mk({lit(C)});\n"
        body += near("(a + b).to_raw()", a + b, 0) + near("(a - b).to_raw()", a - b, 0)
        body += near("(a * b).to_raw()", a * b, 1) + near("(a / b).to_raw()", a / b, 1)
        body += near("(a / c).to_raw()", a / c, 1) + near("(b * b).to_raw()", b * b, 1)
        body += near("(-a).to_raw()", -a, 0) + near("b.abs().to_raw()", -b, 0)
        body += near("a.sqrt().to_raw()", Fraction(math.sqrt(float(a))), 2)
        body += near("b.floor().to_raw()", Fraction(-3), 0) + near("a.floor().to_raw()", Fraction(3), 0)
        body += near("b.round().to_raw()", Fraction(-3), 0) + near("c.round().to_raw()", Fraction(1), 0)
        body += f"    assert!(b.to_int() == -3);\n    assert!(a.to_int() == 3);\n"
        body += f"    let m7: {T} = Real::from_int(-7);\n    assert!(m7.to_raw() == {-7 * ONE});\n"
        body += "    assert!(b < a);\n    assert!(!(a < b));\n    assert!(c < a);\n    assert!(c <= c);\n    assert!(!(a <= c));\n    assert!(a == a);\n    assert!(a != b);\n"
        body += f"    let v1: Vec3<{T}> = mk_vec3({vec(V1)});\n    let v2: Vec3<{T}> = mk_vec3({vec(V2)});\n"
        body += near("glam::dot(v1, v2).to_raw()", dot, 4)
        body += "    let cr = glam::cross(v1, v2);\n"
        for i, f in enumerate("xyz"):
            body += near(f"cr.{f}.to_raw()", cross[i], 4)
        body += near("glam::length(v1).to_raw()", Fraction(ln), 4)
        body += "    let n = glam::normalize(v1);\n"
        for i, f in enumerate("xyz"):
            body += near(f"n.{f}.to_raw()", Fraction(float(v1[i]) / ln), 16)
        body += f"    let m3a: Mat3<{T}> = mk_mat3({span(M3A)});\n    let m3b: Mat3<{T}> = mk_mat3({span(M3B)});\n"
        body += "    let mv = glam::mat3_mul_vec3(m3a, v1);\n"
        for i, f in enumerate("xyz"):
            body += near(f"mv.{f}.to_raw()", mv[i], 4)
        body += "    let mm = glam::mat3_mul_mat3(m3a, m3b);\n"
        for ci, col in enumerate(["x_axis", "y_axis", "z_axis"]):
            for ri, f in enumerate("xyz"):
                body += near(f"mm.{col}.{f}.to_raw()", mm[3 * ci + ri], 4)
        body += f"    let m4a: Mat4<{T}> = mk_mat4({span(M4A)});\n    let m4b: Mat4<{T}> = mk_mat4({span(M4B)});\n"
        body += "    let m4 = glam::mat4_mul_mat4(m4a, m4b);\n"
        for ci, col in enumerate(["x_axis", "y_axis", "z_axis", "w_axis"]):
            for ri, f in enumerate("xyzw"):
                body += near(f"m4.{col}.{f}.to_raw()", m4[4 * ci + ri], 5)
        body += f"    let q1: Quat<{T}> = mk_quat({vec(Q1)});\n    let q2: Quat<{T}> = mk_quat({vec(Q2)});\n"
        body += "    let qm = glam::quat_mul(q1, q2);\n"
        for i, f in enumerate("xyzw"):
            body += near(f"qm.{f}.to_raw()", qm[i], 5)
        body += "    let rot = glam::quat_rotate(q1, v1);\n"
        for i, f in enumerate("xyz"):
            body += near(f"rot.{f}.to_raw()", rot[i], 32)
        out.append(f"mod {tag} {{\n    use super::*;\n    use {ty};\n    #[test]\n    fn check() {{\n{body}}}\n}}\n")
    return "\n".join(out)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    for fname, content in [("scalar.cairo", scalar_tests()), ("composite.cairo", composite_tests()),
                           ("correctness.cairo", correctness_tests())]:
        with open(os.path.join(here, "..", "tests", fname), "w") as f:
            f.write(content)
        print("wrote tests/" + fname)


if __name__ == "__main__":
    main()
