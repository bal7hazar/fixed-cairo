#!/usr/bin/env python3
"""Generates src/prims_tables.cairo: lookup tables in their different encodings."""
import os

def lut_val(i):
    return (i * 0x9E3779B97F4A7C15 + 12345) % (1 << 63)

out = ["// GENERATED by scripts/gen_tables.py -- do not edit by hand.\n"]
out.append("pub const POW2_TABLE: [u64; 64] = [" + ", ".join(hex(1 << i) for i in range(64)) + "];\n")
out.append("pub const LUT64: [u64; 64] = [" + ", ".join(hex(lut_val(i)) for i in range(64)) + "];\n")
out.append("pub const LUT256: [u64; 256] = [" + ", ".join(hex(lut_val(i)) for i in range(256)) + "];\n")
out.append("pub const LUT64_PAIRS: [(u64, u64); 64] = [" + ", ".join(f"({hex(lut_val(i))}, {hex(i)})" for i in range(64)) + "];\n")

def match_fn(name, ty, n, f):
    arms = "\n".join(f"        {i} => {hex(f(i))}," for i in range(n))
    return f"pub fn {name}(i: {ty}) -> u64 {{\n    match i {{\n{arms}\n        _ => core::panic_with_felt252('oob'),\n    }}\n}}\n"

out.append(match_fn("pow2_match", "u32", 64, lambda i: 1 << i))
out.append(match_fn("lut64_match", "u32", 64, lut_val))
out.append(match_fn("lut64_match_felt", "felt252", 64, lut_val))
out.append(match_fn("lut8_match", "u32", 8, lut_val))
out.append(match_fn("lut256_match", "u32", 256, lut_val))
chain = "pub fn lut8_if(i: u32) -> u64 {\n    " + " else ".join(f"if i == {i} {{ {hex(lut_val(i))} }}" for i in range(8)) + " else { core::panic_with_felt252('oob') }\n}\n"
out.append(chain)
out.append("pub fn build_array64() -> Array<u64> {\n    array![" + ", ".join(hex(lut_val(i)) for i in range(64)) + "]\n}\n")
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "..", "src", "prims_tables.cairo"), "w").write("\n".join(out))
print("wrote src/prims_tables.cairo")
