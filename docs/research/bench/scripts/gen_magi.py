#!/usr/bin/env python3
"""Generates src/fixed/magi.cairo (A') from src/fixed/mag.cairo (A): same sign-magnitude code with
`#[inline(always)]` on the hot operators and the cheap `wide_mul` scaling in sqrt."""
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "..", "src", "fixed", "mag.cairo")).read()
s = src.replace("FMag", "FMagI")
s = "// GENERATED by scripts/gen_magi.py from mag.cairo -- do not edit by hand.\n//! A': inline(always) variant of A.\n" + s
s = re.sub(r"\n    fn (add|sub|neg|mul|div|eq|lt|le|abs)\(", lambda m: "\n    #[inline(always)]\n    fn %s(" % m.group(1), s)
s = s.replace("let scaled: u128 = self.mag.into() * ONE.into();", "let scaled: u128 = WideMul::wide_mul(self.mag, ONE);")
open(os.path.join(here, "..", "src", "fixed", "magi.cairo"), "w").write(s)
print("wrote src/fixed/magi.cairo")
