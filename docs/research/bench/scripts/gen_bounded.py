#!/usr/bin/env python3
"""Generates src/fixed/i64b_types.cairo: BoundedInt helper impls for the i64 Q32.32 kernels.

For an accumulator made of K raw products (each in [-M, P], P = 2^126, M = 2^126 - 2^63) we need:
  acc + OFF      (OFF multiple of 2^32, >= K*M so that the dividend is non-negative)
  div_rem 2^32   (floor)
  q - OFF/2^32
Every bound below is computed here so that the Cairo side contains no hand-typed constants.
"""
import os

P = 1 << 126
M = P - (1 << 63)
SH = 1 << 32


def h(v):
    return ("-" if v < 0 else "") + hex(abs(v))


def bi(lo, hi):
    return f"BoundedInt<{h(lo)}, {h(hi)}>"


out = ["// GENERATED by scripts/gen_bounded.py -- do not edit by hand.",
       "#[feature(\"bounded-int-utils\")]",
       "use core::internal::bounded_int::{",
       "    self, AddHelper, BoundedInt, DivRemHelper, MulHelper, SubHelper, UnitInt, downcast,",
       "};",
       ""]
out.append(f"pub type Prod1 = {bi(-M, P)};")
out.append("pub impl MulI64I64 of MulHelper<i64, i64> {\n    type Result = Prod1;\n}")
# accumulators: name -> (lo, hi)
accs = {"Prod1": (-M, P), "Prod2": (-2 * M, 2 * P), "Prod3": (-3 * M, 3 * P), "Prod4": (-4 * M, 4 * P),
        "ProdDiff": (-M - P, P + M)}
for n in ("Prod2", "Prod3", "Prod4", "ProdDiff"):
    out.append(f"pub type {n} = {bi(*accs[n])};")
out.append("pub impl AddProd1Prod1 of AddHelper<Prod1, Prod1> {\n    type Result = Prod2;\n}")
out.append("pub impl AddProd2Prod1 of AddHelper<Prod2, Prod1> {\n    type Result = Prod3;\n}")
out.append("pub impl AddProd3Prod1 of AddHelper<Prod3, Prod1> {\n    type Result = Prod4;\n}")
out.append("pub impl SubProd1Prod1 of SubHelper<Prod1, Prod1> {\n    type Result = ProdDiff;\n}")
consts = []
for n, (lo, hi) in accs.items():
    off = SH
    while off < -lo:
        off <<= 1
    olo, ohi = lo + off, hi + off
    qlo, qhi = olo // SH, ohi // SH
    qoff = off // SH
    out.append(f"// ---- {n}: offset 2^{off.bit_length() - 1}")
    out.append(f"pub type {n}Off = {bi(olo, ohi)};")
    out.append(f"pub impl Add{n}Offset of AddHelper<{n}, UnitInt<{h(off)}>> {{\n    type Result = {n}Off;\n}}")
    out.append(f"pub type {n}Quot = {bi(qlo, qhi)};")
    out.append(f"pub impl DivRem{n}Off of DivRemHelper<{n}Off, UnitInt<{h(SH)}>> {{\n    type DivT = {n}Quot;\n    type RemT = {bi(0, SH - 1)};\n}}")
    out.append(f"pub type {n}Res = {bi(qlo - qoff, qhi - qoff)};")
    out.append(f"pub impl Sub{n}Offset of SubHelper<{n}Quot, UnitInt<{h(qoff)}>> {{\n    type Result = {n}Res;\n}}")
    out.append(
        f"/// floor({n} / 2^32), range-checked into i64 (the only runtime overflow check).\n"
        f"#[inline(always)]\npub fn narrow_{n.lower()}(p: {n}) -> i64 {{\n"
        f"    let po = bounded_int::add::<_, UnitInt<{h(off)}>>(p, {h(off)});\n"
        f"    let (q, _r) = bounded_int::div_rem::<_, UnitInt<{h(SH)}>>(po, {h(SH)});\n"
        f"    let r = bounded_int::sub::<_, UnitInt<{h(qoff)}>>(q, {h(qoff)});\n"
        f"    downcast(r).expect('fixed overflow')\n}}"
    )

# division: |a| * 2^32 / |b|
out.append("// ---- division: (|a| << 32) / |b|")
A = 1 << 63
out.append(f"pub type AbsI64 = {bi(0, A)};\npub type PosI64 = {bi(0, A - 1)};\npub type NegatedNegI64 = {bi(1, A)};")
out.append(f"pub type Num = {bi(0, A * SH)};")
out.append(f"pub impl MulAbsOne of MulHelper<AbsI64, UnitInt<{h(SH)}>> {{\n    type Result = Num;\n}}")
out.append(f"pub impl DivRemNumPos of DivRemHelper<Num, PosI64> {{\n    type DivT = Num;\n    type RemT = {bi(0, A - 2)};\n}}")
out.append(f"pub impl DivRemNumNeg of DivRemHelper<Num, NegatedNegI64> {{\n    type DivT = Num;\n    type RemT = {bi(0, A - 1)};\n}}")
out.append(f"pub impl NegNum of MulHelper<Num, UnitInt<-1>> {{\n    type Result = {bi(-A * SH, 0)};\n}}")
out.append("// ---- floor: raw - frac")
out.append(f"pub impl AddI64Bias of AddHelper<i64, UnitInt<{h(1 << 63)}>> {{\n    type Result = {bi(0, (1 << 64) - 1)};\n}}")
out.append(f"pub impl DivRemU64One of DivRemHelper<{bi(0, (1 << 64) - 1)}, UnitInt<{h(SH)}>> {{\n    type DivT = {bi(0, SH - 1)};\n    type RemT = {bi(0, SH - 1)};\n}}")
out.append(f"pub impl SubIntBias of SubHelper<{bi(0, SH - 1)}, UnitInt<{h(1 << 31)}>> {{\n    type Result = {bi(-(1 << 31), (1 << 31) - 1)};\n}}")
out.append(f"pub impl SubI64Frac of SubHelper<i64, {bi(0, SH - 1)}> {{\n    type Result = {bi(-(1 << 63) - SH + 1, (1 << 63) - 1)};\n}}")
out.append(f"pub impl MulI32One of MulHelper<i32, UnitInt<{h(SH)}>> {{\n    type Result = {bi(-(1 << 63), ((1 << 31) - 1) * SH)};\n}}")
out.append(f"pub impl MulU64One of MulHelper<u64, UnitInt<{h(SH)}>> {{\n    type Result = {bi(0, ((1 << 64) - 1) * SH)};\n}}")
out.append("// ---- felt252-backed representation: narrow an i128-ranged accumulator")
U128M = (1 << 128) - 1
out.append(f"pub type U128B = {bi(0, U128M)};")
out.append(f"pub impl AddI128Bias of AddHelper<i128, UnitInt<{h(1 << 127)}>> {{\n    type Result = U128B;\n}}")
out.append(f"pub type U96B = {bi(0, (1 << 96) - 1)};")
out.append(f"pub impl DivRemU128One of DivRemHelper<U128B, UnitInt<{h(SH)}>> {{\n    type DivT = U96B;\n    type RemT = {bi(0, SH - 1)};\n}}")
out.append(f"pub impl SubU96Bias of SubHelper<U96B, UnitInt<{h(1 << 95)}>> {{\n    type Result = {bi(-(1 << 95), (1 << 95) - 1)};\n}}")
out.append("// ---- Q64.64 recombination: hi * 2^64 + (lo >> 64)")
U64M = (1 << 64) - 1
out.append(f"pub type HiShifted = {bi(0, U64M << 64)};")
out.append(f"pub impl MulU64Two64 of MulHelper<u64, UnitInt<{h(1 << 64)}>> {{\n    type Result = HiShifted;\n}}")
out.append(f"pub type U64B = {bi(0, U64M)};")
out.append(f"pub impl DivRemU128Two64 of DivRemHelper<u128, UnitInt<{h(1 << 64)}>> {{\n    type DivT = U64B;\n    type RemT = U64B;\n}}")
out.append(f"pub impl MulU64BTwo64 of MulHelper<U64B, UnitInt<{h(1 << 64)}>> {{\n    type Result = HiShifted;\n}}")
out.append(f"pub impl AddHiLo of AddHelper<HiShifted, U64B> {{\n    type Result = U128B;\n}}")
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "..", "src", "fixed", "i64b_types.cairo"), "w").write("\n".join(out) + "\n")
print("wrote src/fixed/i64b_types.cairo")
